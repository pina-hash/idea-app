#!/usr/bin/env node
// tools/connector/levels-table.mjs
//
// WRITES THE SAFETY-LEVEL TABLE IN docs/connector/DESIGN.md SECTION 7 FROM THE
// COMPILED OVERLAY, between its two markers, stamped with the day it was
// written. The overlay is what the server enforces, so the table can never
// say one thing while the server does another. Run by `npm run connector:build`
// after the overlay compiles; tests/connector-coverage.test.ts fails on a
// stale table (the stamp line aside).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DESIGN_PATH = fileURLToPath(new URL('../../docs/connector/DESIGN.md', import.meta.url));
export const OVERLAY_JSON = fileURLToPath(new URL('../../src/lib/server/connector/overlay.generated.json', import.meta.url));
export const START = '<!-- levels:start (generated by tools/connector/levels-table.mjs from the overlay; edit the YAML, not this table) -->';
export const END = '<!-- levels:end -->';

const FAMILY = {
	'armory.yaml': 'IDEA Armory',
	'certifications.yaml': 'Certifications',
	'classroom.yaml': 'IDEA Classroom',
	'coin.yaml': 'IDEA Coin',
	'connector.yaml': 'The connector itself',
	'foundry.yaml': 'Foundry',
	'gauntlet.yaml': 'GAUNTLET',
	'greenline.yaml': 'GREENLINE',
	'ideacad.yaml': 'IdeaCAD',
	'maps.yaml': 'IDEA Maps',
	'notebook.yaml': 'Notebook',
	'site.yaml': 'People, feedback and the rest of the site',
	'tournaments.yaml': 'Tournaments',
	'endpoints.yaml': 'Site routes (run in-process as him)'
};

function words(rule) {
	if (rule.if !== undefined) return `${rule.level} when ${rule.if}`;
	return `otherwise ${rule.else}`;
}

function nameOf(key, e) {
	return e.tool && e.tool !== key ? `\`${key}\` (${e.tool})` : `\`${key}\``;
}

/** The table, as markdown lines, from the compiled overlay. Deterministic: no date in it. */
export function renderLevelsTable(overlay) {
	const groups = new Map();
	const add = (file, kind, text) => {
		const fam = FAMILY[file] ?? file;
		if (!groups.has(fam)) groups.set(fam, { read: [], undo: [], confirm: [], rule: [], excluded: [] });
		groups.get(fam)[kind].push(text);
	};
	for (const [key, e] of Object.entries(overlay.functions)) {
		const file = overlay.sources[key];
		if (e.exclude !== undefined) add(file, 'excluded', `\`${key}\``);
		else if (e.level_when?.length) add(file, 'rule', `${nameOf(key, e)}: ${e.level_when.map(words).join(', ')}`);
		else add(file, e.level ?? 'confirm', nameOf(key, e));
	}
	for (const [route, e] of Object.entries(overlay.endpoints)) {
		if (e.exclude !== undefined) add('endpoints.yaml', 'excluded', `\`${route}\``);
		else add('endpoints.yaml', e.level ?? 'confirm', `\`${route}\` (${e.tool})`);
	}
	const fams = [...groups.keys()].sort((a, b) => a.localeCompare(b));
	const total = { read: 0, undo: 0, confirm: 0, rule: 0, excluded: 0 };
	const lines = [];
	lines.push('| Family | read | undo (runs, logged) | confirm (asks first) | by argument | excluded |');
	lines.push('|---|---|---|---|---|---|');
	for (const f of fams) {
		const g = groups.get(f);
		for (const k of Object.keys(total)) total[k] += g[k].length;
		lines.push(`| ${f} | ${g.read.length} | ${g.undo.length} | ${g.confirm.length} | ${g.rule.length} | ${g.excluded.length} |`);
	}
	lines.push(`| **All** | **${total.read}** | **${total.undo}** | **${total.confirm}** | **${total.rule}** | **${total.excluded}** |`);
	lines.push('');
	for (const f of fams) {
		const g = groups.get(f);
		lines.push(`<details><summary>${f}</summary>`);
		lines.push('');
		for (const [kind, label] of [
			['read', 'Read'],
			['undo', 'Undo'],
			['confirm', 'Asks first'],
			['rule', 'By argument'],
			['excluded', 'Excluded (the reason is in the YAML)']
		]) {
			if (!g[kind].length) continue;
			lines.push(`- **${label}:** ${[...g[kind]].sort().join(', ')}`);
		}
		lines.push('');
		lines.push('</details>');
		lines.push('');
	}
	return lines;
}

export function stampLine(dayIso) {
	return `Generated from the overlay on ${dayIso}.`;
}

/** The text between the markers, stamp line dropped, for comparing. */
export function tableInDesign(text) {
	const a = text.indexOf(START);
	const b = text.indexOf(END);
	if (a < 0 || b < a) return null;
	return text
		.slice(a + START.length, b)
		.split('\n')
		.filter((l) => !l.startsWith('Generated from the overlay on '))
		.join('\n')
		.trim();
}

function main() {
	const overlay = JSON.parse(readFileSync(OVERLAY_JSON, 'utf8'));
	const text = readFileSync(DESIGN_PATH, 'utf8');
	const a = text.indexOf(START);
	const b = text.indexOf(END);
	if (a < 0 || b < a) throw new Error('DESIGN.md has no levels markers in section 7.');
	const today = new Date().toLocaleDateString('en-CA', { timeZone: 'America/Los_Angeles' });
	const body = ['', stampLine(today), '', ...renderLevelsTable(overlay), ''].join('\n');
	const before = tableInDesign(text);
	const next = text.slice(0, a + START.length) + body + text.slice(b);
	if (before === tableInDesign(next)) {
		console.log('levels table: unchanged');
		return;
	}
	writeFileSync(DESIGN_PATH, next);
	console.log(`levels table: written (${today})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
