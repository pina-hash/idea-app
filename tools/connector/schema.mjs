#!/usr/bin/env node
// tools/connector/schema.mjs
//
// LAYER 2 OF THE CONNECTOR REGISTRY: boots an embedded Postgres, applies every
// migration (tools/connector/cluster.mjs, the same three inputs the full-chain
// suites apply) and writes what pg_proc says about every inventoried function,
// every function the overlay names, and every connector_ function, to
// src/lib/server/connector/schema.generated.json. Nothing about a function's
// arguments is typed by hand anywhere in the registry: this file is where the
// names, types and defaults come from.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { bootFullChain, REPO_ROOT } from './cluster.mjs';
import { readSchema } from './schema-query.mjs';

export const SCHEMA_PATH = join(REPO_ROOT, 'src/lib/server/connector/schema.generated.json');
const INVENTORY = join(REPO_ROOT, 'src/lib/server/connector/inventory.generated.json');
const OVERLAY = join(REPO_ROOT, 'src/lib/server/connector/overlay.generated.json');

/** Every function name the schema layer must describe. */
export function schemaNames(inventory, overlay) {
	const names = new Set(inventory.functions);
	for (const [name, entry] of Object.entries(overlay?.functions ?? {})) {
		names.add(name);
		if (entry?.undo?.function) names.add(entry.undo.function);
	}
	for (const tool of Object.values(overlay?.tools ?? {})) {
		for (const fn of tool?.uses ?? []) names.add(fn);
	}
	return [...names].filter((n) => /^[a-z][a-z0-9_]*$/.test(n)).sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const inventory = JSON.parse(readFileSync(INVENTORY, 'utf8'));
	let overlay = null;
	try {
		overlay = JSON.parse(readFileSync(OVERLAY, 'utf8'));
	} catch {
		overlay = null;
	}
	const { client, stop, files } = await bootFullChain();
	try {
		const schema = await readSchema((t, p) => client.query(t, p), schemaNames(inventory, overlay));
		const body = {
			note: 'Generated by tools/connector/schema.mjs (npm run connector:build) from every migration applied to an embedded Postgres. Do not edit by hand.',
			migrations: files.length,
			last_migration: files[files.length - 1],
			functions: schema
		};
		writeFileSync(SCHEMA_PATH, JSON.stringify(body, null, '\t') + '\n');
		const missing = Object.entries(schema).filter(([, v]) => v.length === 0).map(([k]) => k);
		console.log(`schema: ${Object.keys(schema).length} names, ${missing.length} with no function in the database`);
	} finally {
		await stop();
	}
}
