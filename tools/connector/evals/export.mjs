#!/usr/bin/env node
// tools/connector/evals/export.mjs
//
// REGENERATES docs/connector/EVALS.md FROM THE SAVED REQUESTS TABLE
// (`connector_evals`, 0272), so the file stays readable and the table stays the
// source (docs/connector/DESIGN.md section 9).
//
//   node tools/connector/evals/export.mjs --json <file>
//       From the list Mr. Pina downloads on /admin/connector ("Download the
//       list"): the production table, with every request he has added and the
//       last practice replay of each. This is the ordinary way in.
//
//   node tools/connector/evals/export.mjs
//       From an embedded Postgres with every migration applied: the table as
//       0272 seeds it. What a fresh database holds, never what production does.
//
//   --check   writes nothing; exits 1 when the file differs from what it would write.
//
// It reads no environment variable and holds no credential: production reaches
// it only as a file a signed-in admin downloaded.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const EVALS_PATH = fileURLToPath(new URL('../../../docs/connector/EVALS.md', import.meta.url));
export const GENERATED_MARK = '<!-- generated by tools/connector/evals/export.mjs; edit the table, not this file -->';

const LETTER = { read: 'R', undo: 'U', confirm: 'C', refuse: 'X' };

const INTRO = `# Connector evals: the finish line

${GENERATED_MARK}

Things Mr. Pina says to Claude, by voice, from a fresh chat on his phone with
the IDEA Website connector on. Each names what must happen and what proves it:
a row in the production database read back afterwards (the Supabase SQL editor,
read-only), never the chat's own report. A run passes when every line passes
from one fresh chat. Student names in the first fifty are placeholders; the run
uses real names from his rosters, and lines 41 to 45 need a name that really is
ambiguous in one of his classes.

The list lives in the database (\`connector_evals\`, ledger 0401), seeded from
the original fifty lines plus two, and it grows: every request he makes whose
words match no line here is added automatically, with the path that served it
as its expected path. Anything the connector cannot do is logged as a gap in
the Connector feedback section (\`/admin/feedback/connector\`). This file is
regenerated from the table by \`tools/connector/evals/export.mjs\`; the target
model is Haiku 5.5 (DESIGN.md section 8), and the nightly practice replay
records each line's last result (\`connector_eval_runs\`).

Legend: **R** read, **U** undoable write, **C** asks first, **X** refused or asked.
`;

function cell(text) {
	return String(text ?? '')
		.replace(/\r?\n/g, ' ')
		.replace(/\|/g, '\\|')
		.trim();
}

function day(iso) {
	return typeof iso === 'string' && /^\d{4}-\d{2}-\d{2}/.test(iso) ? iso.slice(0, 10) : '';
}

/** One table row for one saved request. */
export function renderRow(r) {
	const path = (r.expected_path ?? []).map((t) => `\`${t}\``).join(', ');
	const must = r.must_happen ?? '';
	const origin = r.source === 'request' ? `From his request, ${day(r.created_at)}` : '';
	const run = r.last_run ? `${r.last_run.passed ? 'pass' : 'FAIL'} ${day(r.last_run.run_at)}` : '';
	return `| ${r.seq} | ${cell(r.said)} | ${LETTER[r.level] ?? '?'} | ${cell(must)} | ${cell(r.proof ?? '')} | ${path} | ${cell([origin, run].filter(Boolean).join('; '))} |`;
}

/** The whole file, from the saved requests in their order. */
export function renderEvals(rows) {
	const sorted = [...rows].sort((a, b) => a.seq - b.seq);
	const lines = [
		INTRO,
		`${sorted.length} saved requests, ${sorted.filter((r) => r.source === 'request').length} of them added from his own requests.`,
		'',
		'| # | He says | Level | Must happen | Proof | Expected path | Notes |',
		'|---|---|---|---|---|---|---|',
		...sorted.map(renderRow),
		''
	];
	return lines.join('\n');
}

/** The seed file's shape, as the table holds it after 0272. */
export function seedRows(seed) {
	return seed.map((s) => ({
		seq: s.n,
		said: s.said,
		level: s.level,
		must_happen: s.must ?? null,
		proof: s.proof ?? null,
		expected_path: s.path ?? [],
		source: 'seed',
		created_at: null,
		last_run: null
	}));
}

async function fromCluster() {
	const { bootFullChain } = await import('../cluster.mjs');
	const db = await bootFullChain({ log: (m) => console.error(m) });
	try {
		const { rows } = await db.client.query(
			`select e.seq, e.said, e.level, e.must_happen, e.proof, e.expected_path, e.source, e.created_at::text as created_at,
			        (select jsonb_build_object('passed', r.passed, 'run_at', r.run_at) from public.connector_eval_runs r
			         where r.eval_id = e.id order by r.run_at desc limit 1) as last_run
			 from public.connector_evals e where e.retired_at is null order by e.seq`
		);
		return rows;
	} finally {
		await db.stop();
	}
}

async function main() {
	const args = process.argv.slice(2);
	const jsonAt = args.indexOf('--json');
	const check = args.includes('--check');
	let rows;
	if (jsonAt >= 0) {
		const file = args[jsonAt + 1];
		if (!file) throw new Error('--json needs the downloaded file.');
		const parsed = JSON.parse(readFileSync(file, 'utf8'));
		rows = Array.isArray(parsed) ? parsed : parsed.evals;
		if (!Array.isArray(rows)) throw new Error('That file is not the saved requests list from /admin/connector.');
	} else {
		rows = await fromCluster();
	}
	const text = renderEvals(rows);
	const current = (() => {
		try {
			return readFileSync(EVALS_PATH, 'utf8');
		} catch {
			return '';
		}
	})();
	if (check) {
		if (current !== text) {
			console.error('docs/connector/EVALS.md is not what the table would write. Run node tools/connector/evals/export.mjs.');
			process.exit(1);
		}
		console.log(`EVALS.md matches ${rows.length} saved requests.`);
		return;
	}
	writeFileSync(EVALS_PATH, text);
	console.log(`EVALS.md: ${rows.length} saved requests written.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	main().catch((e) => {
		console.error(e instanceof Error ? e.message : e);
		process.exit(1);
	});
}
