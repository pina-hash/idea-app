/**
 * Writes `tests/fixtures/tab-icon-golden.json` from the ORIGINAL design module.
 *
 *   node tools/tab-icon/golden.mjs <path to idea-tab-icon.js>
 *
 * WHY THIS EXISTS. The tab icon's geometry was decided on a design board and
 * handed over as one plain JavaScript module, `idea-tab-icon.js` (ledger 0396).
 * `src/lib/tab-icon/geometry.ts` is a TypeScript port of the ONE base Mr. Pina
 * chose (Gear Key), with the three bases he did not pick deleted. A port is a
 * retyping, and a retyping can change a coordinate without anyone noticing, so
 * this fixture is recorded from the module AS IT WAS HANDED OVER, mechanically,
 * before anything was extracted (CLAUDE.md, "Characterize behaviour BEFORE
 * extracting it"). `tests/tab-icon-geometry.test.ts` puts every case back
 * through the port and compares.
 *
 * THE ORIGINAL MODULE IS NOT COMMITTED, only what it produced. The cases are a
 * cross product of every section (and a null one), every status at several
 * phases, progress fractions and unread counts, and two gradient-id prefixes,
 * so a change to any shape, colour, phase formula or id spelling moves a hash.
 * Each case stores the first 16 hex characters of the SHA-256 of the SVG; the
 * three home-screen icons and a handful of tab icons are stored whole as well,
 * so a failure there can be read rather than only detected.
 *
 * A KEY IS ITS OWN ARGUMENT LIST, so the test rebuilds the call from the key
 * and has no second copy of the case list to drift from this one.
 */
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const source = process.argv[2];
if (!source) {
	console.error('usage: node tools/tab-icon/golden.mjs <path to idea-tab-icon.js>');
	process.exit(2);
}
const sourcePath = resolve(source);
const require = createRequire(import.meta.url);
const I = require(sourcePath);

const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);

const sections = [null, ...Object.keys(I.G)];
const PHASES = [0, 0.125, 0.25, 0.375, 0.625, 0.875];
const statuses = [
	null,
	{ kind: 'none' },
	{ kind: 'unread', n: 1 },
	{ kind: 'unread', n: 12 },
	{ kind: 'error' },
	{ kind: 'attention' },
	...PHASES.map((phase) => ({ kind: 'live', phase })),
	...PHASES.map((phase) => ({ kind: 'saving', phase })),
	...[0, 0.37, 0.999, 1].map((p) => ({ kind: 'progress', p })),
	{ kind: 'done' },
	{ kind: 'offline' }
];
const UIDS = [null, 'x9'];

/** `icon|<section>|<kind>|<n>|<p>|<phase>|<uid>`, with `-` for absent. */
function keyOf(section, status, uid) {
	const s = status ?? {};
	const part = (v) => (v === undefined || v === null ? '-' : String(v));
	return ['icon', part(section), status ? s.kind : '-', part(s.n), part(s.p), part(s.phase), part(uid)].join('|');
}

const cases = {};
for (const section of sections)
	for (const status of statuses)
		for (const uid of UIDS) {
			const svg = I.icon('gearkey', section, status, uid ?? undefined);
			cases[keyOf(section, status, uid)] = hash(svg);
		}
for (const kind of ['ios', 'android', 'maskable']) cases[`app|${kind}`] = hash(I.appIcon('gearkey', kind));

const fullKeys = [
	keyOf(null, null, null),
	keyOf('home', { kind: 'error' }, null),
	keyOf('home', { kind: 'live', phase: 0 }, null),
	keyOf('home', { kind: 'offline' }, null),
	keyOf('classroom', { kind: 'progress', p: 0.37 }, null),
	keyOf('frc', { kind: 'unread', n: 12 }, null),
	keyOf('certs', { kind: 'saving', phase: 0.125 }, 'x9')
];
const full = {};
for (const k of fullKeys) {
	const [, section, kind, n, p, phase, uid] = k.split('|');
	const un = (v) => (v === '-' ? undefined : v);
	const status = kind === '-' ? null : { kind, n: un(n) && Number(n), p: un(p) && Number(p), phase: un(phase) && Number(phase) };
	full[k] = I.icon('gearkey', un(section) ?? null, status, un(uid));
}
for (const kind of ['ios', 'android', 'maskable']) full[`app|${kind}`] = I.appIcon('gearkey', kind);

const out = {
	note: 'Generated by tools/tab-icon/golden.mjs from the idea-tab-icon.js design module (ledger 0396). Do not edit by hand.',
	source_sha256: createHash('sha256').update(readFileSync(sourcePath)).digest('hex'),
	sections: sections.map((s) => s ?? '-'),
	case_count: Object.keys(cases).length,
	cases,
	full
};
const target = new URL('../../tests/fixtures/tab-icon-golden.json', import.meta.url);
writeFileSync(target, JSON.stringify(out, null, '\t') + '\n');
console.log(`wrote ${out.case_count} cases and ${Object.keys(full).length} whole SVGs`);
