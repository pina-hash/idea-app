#!/usr/bin/env node
/**
 * THE THUMBNAIL SHELL'S FACES AND COLORS (ledger 0458, report f3a3a687).
 *
 *   node tools/hx-thumb-shell.mjs        writes src/lib/classroom/html-assignment/thumbnail-shell.generated.ts
 *
 * A post's live thumbnail is drawn by `thumbnailDocument` from a template in the
 * assignment, and its shell carried no fonts and no color tokens, so every
 * template typed its own hex colors and fell back to system fonts, unlike the
 * page it advertises. This writes, into a generated module the shell inlines:
 *
 *   - the site's two faces a thumbnail needs, Rajdhani 600 and Share Tech Mono,
 *     as data: URIs (the served thumbnail's CSP admits `font-src data:`);
 *   - the kit's own tokens for both themes, from `tools/hx-kit/build.mjs`'s
 *     `tokensCss` (called, not copied), with its theme switch moved from
 *     `data-theme` to the `data-idea-scheme` the thumbnail shim sets.
 *
 * Generated rather than built at request time because `thumbnail.ts` is also
 * bundled by `tools/hx-kit/test.mjs` with esbuild, which knows no Vite import.
 * `tests/html-thumbnail-shell.test.ts` regenerates it and fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokensCss } from './hx-kit/build.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(REPO, 'src/lib/classroom/html-assignment/thumbnail-shell.generated.ts');

const FACES = [
	['Rajdhani', 600, 'rajdhani/files/rajdhani-latin-600-normal.woff2'],
	['Share Tech Mono', 400, 'share-tech-mono/files/share-tech-mono-latin-400-normal.woff2']
];

export function shellCss() {
	const faces = FACES.map(([family, weight, file]) => {
		const b64 = readFileSync(join(REPO, 'node_modules/@fontsource', file)).toString('base64');
		return `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format('woff2')}`;
	}).join('\n');
	const tokens = tokensCss(JSON.parse(readFileSync(join(REPO, 'tools/hx-kit/kit/tokens.json'), 'utf8')))
		.replace(/:root\[data-theme="dark"\]/g, ':root[data-idea-scheme="dark"]')
		.replace(/:root\[data-theme="light"\]/g, ':root[data-idea-scheme="light"]');
	return `${faces}\n${tokens}`;
}

export function generatedModule(css) {
	return [
		'// GENERATED by tools/hx-thumb-shell.mjs (ledger 0458). Do not edit; run the tool.',
		'// The site faces and the kit tokens a post thumbnail draws with.',
		`export const THUMB_SHELL_CSS = ${JSON.stringify(css)};`,
		''
	].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
	writeFileSync(OUT, generatedModule(shellCss()));
	console.log(`wrote ${OUT}`);
}
