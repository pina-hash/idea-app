// tests/frc-quiz-bank-bias-report.mjs
//
// THE INSTRUMENT. It builds ONE document -- the per-item list, worst first, for
// whoever rewrites the questions -- and sends it to one of two destinations:
//
//   npm run frc:bias          prints it to stdout, for asking the question now
//   npm run frc:bias -- --write   writes docs/frc/quiz-bank-bias-report.md
//
// ONE DOCUMENT AND NOT TWO. A console summary written separately from the
// committed document is a second statement of the same measurement, and the
// two would answer differently the first time somebody edited one of them.
// What is printed is byte-identical to what is written.
//
// It measures NOTHING of its own: every number comes from
// tests/frc-quiz-bank-bias.ts, which is also what frc-quiz-bank-bias.test.ts
// enforces, so the document and the lint cannot disagree about the state of the
// banks. The cooldown schedule comes from src/lib/frc/track.ts, which is what
// the server actually enforces, for the same reason.
//
// (Node 22 strips the type annotations off the `.ts` helper, so this plain
// script imports it directly rather than a second copy of the arithmetic
// existing to serve a document.)

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	BANKS,
	allItems,
	absoluteFreeOption,
	giveaway,
	longestOption,
	articleAgreementOption,
	independenceFrom,
	measureAll,
	nearDuplicatePair,
	ofTheAboveOption,
	runTell,
	shortestOption,
	stemEchoOption,
	techiestOption,
	wordiestOption,
	expectedAttempts,
	expectedCooldownSeconds,
	fixesNeeded,
	correctNeeded,
	passProbability,
	worstFirst
} from './frc-quiz-bank-bias.ts';
import { FRC_QUIZ_COOLDOWNS_SEC, cooldownSecondsForFailStreak } from '../src/lib/frc/track.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '..', 'docs', 'frc', 'quiz-bank-bias-report.md');

const pct = (x) => `${(100 * x).toFixed(1)}%`;
const pct3 = (x) => `${(100 * x).toFixed(3)}%`;

const banks = measureAll();
const items = allItems();
const longTell = runTell(items, longestOption);
const wordTell = runTell(items, wordiestOption);
const absTell = runTell(items, absoluteFreeOption);
// Measured here rather than written down, so a bank edit cannot leave the
// document claiming a dimension is clean after it stopped being.
const echoTell = runTell(items, stemEchoOption);
const aboveTell = runTell(items, ofTheAboveOption);
const articleTell = runTell(items, articleAgreementOption);
const dupTell = runTell(
	items,
	(it) => {
		const pair = nearDuplicatePair(it);
		return pair === null ? null : pair.includes(it.answer) ? it.answer : -1;
	},
	(it) => 2 / it.options.length
);
const shortTell = runTell(items, shortestOption);
const techTell = runTell(items, techiestOption);
const echoIndep = independenceFrom(items, stemEchoOption);
// Per bank, because the durable claim about the echo is per bank: fewer hits than the
// threshold needs means a pass probability of exactly zero at any number of retries.
const echoPerBank = Object.entries(BANKS).map(([unitId, b]) => {
	const t = runTell(b.items, stemEchoOption);
	return { unitId, applies: t.applies, hits: t.hits, need: correctNeeded(b), pass: passProbability(b, stemEchoOption) };
});
const techIndep = independenceFrom(items, techiestOption);
// The retake and workload arithmetic, per bank, in the same pass. `fixesNeeded`
// is where the two numbers a person deciding actually needs come from.
const work = Object.fromEntries(Object.entries(BANKS).map(([id, b]) => [id, fixesNeeded(b)]));
const totalToChance = Object.values(work).reduce((a, f) => a + f.toChance, 0);
const totalToGateHeld = Object.values(work).reduce((a, f) => a + f.toGateHeld, 0);
const mins = (sec) => (sec === Infinity ? '-' : `${(sec / 60).toFixed(0)} min`);
const attemptsOf = (p) => (p <= 0 ? 'never' : expectedAttempts(p).toFixed(2));
const optionCounts = [...new Set(items.map((it) => it.options.length))].sort((a, b) => a - b);
const row = (name, t, verdict) =>
	`| ${name} | ${t.applies} | ${t.applies === 0 ? '-' : `${t.hits} (${pct(t.rate)})`} | ` +
	`${t.applies === 0 ? '-' : pct(t.chance)} | ${verdict} |`;

const esc = (s) => s.replace(/\|/g, '\\|');

const scored = items
	.map((it) => ({
		unitId: it.unitId,
		id: it.id,
		g: giveaway(it),
		stem: it.stem,
		item: it,
		answer: it.options[it.answer],
		answerLen: it.options[it.answer].length,
		bestDistractor: it.options
			.filter((_, i) => i !== it.answer)
			.reduce((a, b) => (b.length > a.length ? b : a), ''),
	}))
	.filter((x) => x.g > 0)
	.sort((a, b) => b.g - a.g);

const L = [];
L.push('# FRC quiz banks: what the option text gives away');
L.push('');
L.push(`Generated ${new Date().toISOString().slice(0, 10)}. **Do not edit this file.** Regenerate it after`);
L.push('editing a bank:');
L.push('');
L.push('```');
L.push('npm run frc:bias              # print it, to ask the question now');
L.push('npm run frc:bias -- --write   # rewrite this file');
L.push('```');
L.push('');
L.push('Every figure comes from `tests/frc-quiz-bank-bias.ts`, which is also what');
L.push('`tests/frc-quiz-bank-bias.test.ts` enforces, so this document and the lint cannot');
L.push('disagree about the state of the banks. **Nothing here suggests wording.** A');
L.push('plausible wrong answer in a technical subject is a teaching judgement, and the');
L.push('generator was written so that it cannot start making one.');
L.push('');
L.push('## The finding');
L.push('');
L.push(`Across the ${Object.keys(BANKS).length} committed banks (${items.length} items), the single longest option is the`);
L.push(`correct one **${longTell.hits} times, ${pct(longTell.hits / items.length)}**, against 25% at chance. Shuffling cannot help:`);
L.push('length is invariant under permutation, so the tell survives every draw.');
L.push('');
L.push('The gate is 90% on a short draw, so the rate turns into a pass rate. A student');
L.push('who knows nothing, always picks the longest option and retakes through the');
const worst = banks[0];
L.push(`cooldown clears ${worst.unitId} in about **${attemptsOf(worst.passLongest)} attempts**.`);
L.push('');
L.push(`**The size of the rewrite: ${totalToGateHeld} items to shut the gate, ${totalToChance} to reach chance.**`);
L.push(`Those are two different jobs and only the first is urgent -- see "How many items"`);
L.push('below.');
L.push('');
L.push('## Per bank, worst first');
L.push('');
L.push('`P(pass)` is the exact probability that ONE attempt passes, hypergeometric over');
L.push("that bank's own draw, against its own test length and 90% threshold.");
L.push('');
L.push('| Bank | Items | Draw | Need | Longest-is-answer | P(pass) longest-only | P(pass) random |');
L.push('|---|---|---|---|---|---|---|');
for (const b of banks)
	L.push(
		`| ${b.unitId} | ${b.items} | ${b.testLength} | ${b.correctNeeded} | ` +
			`${b.longest}/${b.items} (${pct(b.longestRate)}) | **${pct(b.passLongest)}** | ${pct3(b.passRandom)} |`
	);
L.push('');
L.push('## What else leaks, and what does not');
L.push('');
L.push('"Fires on" is the number of items where the heuristic points at an option at');
L.push('all; a tie points at nothing and is neither a hit nor a miss. That is why the');
L.push(`longest-option row reads ${pct(longTell.rate)} of the ${longTell.applies} it fires on, while the headline above`);
L.push(`is ${pct(longTell.hits / items.length)} of all ${items.length} items -- the second is the number a student experiences,`);
L.push('because a tie is a question the trick does not answer.');
L.push('');
L.push('| Dimension | Fires on | Correct | Chance | Verdict |');
L.push('|---|---|---|---|---|');
L.push(row('Longest option (characters)', longTell, '**the dominant tell**'));
L.push(row('Most words', wordTell, 'the same tell, second reading'));
L.push(row('Only option with no absolute ("Only...", "Never...")', absTell, '**certain where it fires**'));
L.push(row('Correct option echoes the stem most', echoTell, `no signal of its own -- see below`));
L.push(
	row(
		'Shortest option',
		shortTell,
		shortTell.hits / items.length < 0.25 ? 'worse than guessing' : 'CHECK: at or above chance'
	)
);
L.push(
	row(
		'Most technical-sounding option',
		techTell,
		techTell.hits / items.length <= 0.25 ? 'chance over the corpus -- see below' : 'CHECK: above chance'
	)
);
L.push(row('Near-duplicate option pair contains the answer', dupTell, dupTell.rate === null || dupTell.rate < dupTell.chance + 0.2 ? 'noise, not a tell' : 'CHECK: above chance'));
L.push(row('"All / none of the above"', aboveTell, aboveTell.applies === 0 ? 'clean: none present' : 'CHECK: present'));
L.push(row('a/an agreement with the stem', articleTell, articleTell.applies === 0 ? 'clean: none present' : 'CHECK: present'));
L.push(`| Option count | ${optionCounts.length > 1 ? items.length : 0} | - | - | ${optionCounts.length === 1 ? `clean: every item offers exactly ${optionCounts[0]}` : `CHECK: mixed (${optionCounts.join(', ')})`} |`);
L.push('');
L.push(`**On the stem-echo row.** Taken alone it looks like a second serious leak: it`);
L.push(`fires on ${echoTell.applies} items and is right on ${echoTell.hits}, ${pct(echoTell.rate)} against ${pct(echoTell.chance)}. It is not a`);
L.push(`way through the gate. Per bank it fires on at most ${Math.max(...echoPerBank.map((b) => b.applies))} items and is right on at most`);
L.push(`${Math.max(...echoPerBank.map((b) => b.hits))}, below what any bank's threshold needs (${echoPerBank.map((b) => `${b.unitId} ${b.hits}/${b.need}`).join(', ')}),`);
L.push(`so a student who answers with the echo where it fires and gets the rest wrong passes`);
L.push(`${pct(Math.max(...echoPerBank.map((b) => b.pass)))} of attempts on the worst bank -- it cannot clear a unit at any number of retries.`);
L.push(`On the ${echoIndep.disagreements} items where it and the length tell point at DIFFERENT options, length is`);
L.push(`right ${echoIndep.baselineRight} times and the echo ${echoIndep.tellRight}; that ratio moves whenever a distractor is lengthened past an`);
L.push('answer that echoes the stem, because the length tell is then wrong on that item by');
L.push('construction, so it describes the state of the length fix rather than the echo.');
L.push('');
L.push('**On the other two strategies.** Neither is a second way through the gate, which');
L.push('is worth stating because if either were, lengthening distractors would not');
L.push('finish the job.');
L.push('');
L.push(`- **Shortest option** is right on ${shortTell.hits} of ${items.length} items (${pct(shortTell.hits / items.length)}), well under chance. On`);
L.push(`  every bank it reaches fewer correct answers than the pass threshold needs, so`);
L.push('  it cannot clear a single unit at any number of retries. It is the length tell');
L.push('  seen from the other end, not an independent fact.');
L.push(`- **Most technical-sounding option** fires on ${techTell.applies} items and is right on ${techTell.hits} of them`);
L.push(`  (${pct(techTell.rate)}), which reads alarming, and is ${pct(techTell.hits / items.length)} of the whole corpus, which is`);
L.push(`  chance. Where it and the length tell disagree (${techIndep.disagreements} items) length is right`);
L.push(`  ${techIndep.baselineRight} times and this ${techIndep.tellRight}. A longer option holds more long words.`);
L.push('');
L.push('## Retaking, which is where the per-attempt numbers stop reassuring');
L.push('');
L.push(`There is **no attempt limit** anywhere in the quiz path. A failure costs a`);
L.push(`cooldown -- ${FRC_QUIZ_COOLDOWNS_SEC.join(', ')} seconds, escalating then holding at the last -- and`);
L.push('nothing else. Attempts are independent: each one reshuffles every item index,');
L.push('and a failed attempt returns a score and the missed topic names, never which');
L.push('questions were wrong, so nothing accumulates between them and no amount of');
L.push('memorising the stems helps. That makes the honest question not "what does one');
L.push('attempt cost" but "how long until it lands".');
L.push('');
L.push('| Bank | P(pass) per attempt | Expected attempts | Expected time waiting |');
L.push('|---|---|---|---|');
for (const b of banks)
	L.push(
		`| ${b.unitId} | ${pct(b.passLongest)} | ${attemptsOf(b.passLongest)} | ` +
			`${mins(expectedCooldownSeconds(b.passLongest, cooldownSecondsForFailStreak))} |`
	);
L.push('');
L.push('## How many items have to be rewritten');
L.push('');
L.push('Two numbers, because they answer two different questions and only one of them');
L.push('decides whether this happens this week.');
L.push('');
L.push('- **Shut the gate** is the smallest number of items whose distractors have to');
L.push('  catch up before a longest-option student passes fewer than 1% of attempts --');
L.push('  the point at which retrying stops being a route through. Worst items first.');
L.push('- **Reach chance** is the full job: the longest option is the answer no more');
L.push('  often than one in four, which is what a bank with no length tell measures.');
L.push('');
L.push('| Bank | To shut the gate | P(pass) after those | To reach chance |');
L.push('|---|---|---|---|');
for (const b of banks)
	L.push(
		`| ${b.unitId} | **${work[b.unitId].toGateHeld}** | ${pct(work[b.unitId].passAfterGateHeld)} | ` +
			`${work[b.unitId].toChance} |`
	);
L.push(`| **Total** | **${totalToGateHeld}** | | **${totalToChance}** |`);
L.push('');
L.push('## The rewrite list');
L.push('');
L.push('Ordered by **give-away**: the correct option\'s length as a multiple of the');
L.push('longest distractor offered against it. 1.0 would mean the answer is no longer');
L.push('than its best distractor and the tell is dead. Items whose answer is not the');
L.push('longest are not listed -- there are ' + (items.length - scored.length) + ' of those, and they are not the problem.');
L.push('');
L.push('**The fix is to lengthen the distractors, not to shorten the answer.** A correct');
L.push('option trimmed until it matches is usually a correct option that stopped being');
L.push('clearly correct.');
L.push('');
L.push('Each item is listed with **every option and its character count**, because a');
L.push('rewrite happens at the whole item: the distractor that has to catch up is one of');
L.push('the three below the answer, and which one is a judgement about the subject.');
L.push('**Target** is the length the longest distractor has to reach for the tell to');
L.push('stop firing on this item -- one character past the answer.');
L.push('');
scored.forEach((x, i) => {
	const target = x.answerLen + 1;
	L.push(
		`### ${i + 1}. ${x.unitId} \`${x.id}\` -- give-away **${x.g.toFixed(2)}x**, ` +
			`longest distractor needs ${target - x.bestDistractor.length} more characters`
	);
	L.push('');
	L.push(`> ${esc(x.stem)}`);
	L.push('');
	x.item.options.forEach((o, oi) => {
		const mark = oi === x.item.answer ? '**answer**' : 'distractor';
		const note =
			oi === x.item.answer
				? ''
				: o === x.bestDistractor
					? ` <- longest distractor; reach ${target} to neutralise`
					: '';
		L.push(`- ${mark} (${o.length}) ${esc(o)}${note}`);
	});
	L.push('');
});
L.push('## The nine absolute-qualifier items');
L.push('');
L.push('Three of the four options are written as absolutes and the answer is not, so');
L.push('the answer is identifiable without reading the question. All nine, listed in');
L.push('full because the fix is per item.');
L.push('');
for (const it of items) {
	const pick = absoluteFreeOption(it);
	if (pick === null) continue;
	L.push(`- **${it.unitId} \`${it.id}\`** -- ${esc(it.stem)}`);
	it.options.forEach((o, i) =>
		L.push(`  - ${i === it.answer ? '**(answer)**' : '(distractor)'} ${esc(o)}`)
	);
}
L.push('');

// ---------------------------------------------------------------------------
// ONE DOCUMENT, TWO DESTINATIONS. `--write` commits it; the default prints it,
// so asking the question costs nothing and leaves no diff. Byte-identical
// either way -- a console summary composed separately would be a second
// statement of the same measurement.
// ---------------------------------------------------------------------------
const doc = L.join('\n');
const summary =
	`${items.length} items, ${longTell.hits} longest-is-answer ` +
	`(${pct(longTell.hits / items.length)}), ${scored.length} on the rewrite list; ` +
	`${totalToGateHeld} to shut the gate, ${totalToChance} to reach chance`;

if (process.argv.includes('--write')) {
	mkdirSync(dirname(out), { recursive: true });
	writeFileSync(out, doc, 'utf8');
	console.log(`wrote ${out}`);
	console.log(`  ${summary}`);
} else {
	process.stdout.write(doc);
	process.stderr.write(`\n${summary}\n(--write to regenerate ${out})\n`);
}
