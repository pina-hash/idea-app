/**
 * Blanks comments while KEEPING every byte's position, so a line number taken
 * from the blanked copy is still true of the original. Newlines survive for the
 * same reason.
 */
function blankComments(source: string, lineComments: boolean): string {
	const out = source.split('');
	let i = 0;
	const n = source.length;
	let quote: string | null = null;
	while (i < n) {
		const ch = source[i];

		// INSIDE A STRING, NOTHING IS A COMMENT. This is not a nicety: the very
		// thing being detected is a URL, every URL contains "//", and a blanker
		// that does not know it is inside a string erases the second half of
		// `import x from "https://esm.sh/y"` and then reports the wreckage back
		// to the student as the thing that is wrong with their file. Measured:
		// the message read `imports from https:` followed by the next line of
		// their program.
		if (quote !== null) {
			if (ch === '\\') {
				i += 2;
				continue;
			}
			if (ch === quote) quote = null;
			i++;
			continue;
		}
		if (ch === '"' || ch === "'" || ch === '`') {
			quote = ch;
			i++;
			continue;
		}

		const two = source.slice(i, i + 2);
		if (two === '/*') {
			let j = source.indexOf('*/', i + 2);
			j = j < 0 ? n : j + 2;
			for (let k = i; k < j && k < n; k++) if (out[k] !== '\n') out[k] = ' ';
			i = j;
			continue;
		}
		if (lineComments && two === '//') {
			let j = source.indexOf('\n', i);
			if (j < 0) j = n;
			for (let k = i; k < j; k++) out[k] = ' ';
			i = j;
			continue;
		}
		i++;
	}
	return out.join('');
}

export function scanCss(path: string, source: string): { failures: FoundryIssue[] } {
	const failures: FoundryIssue[] = [];
	const text = blankComments(source, false);

	const push = (value: string, index: number, attr: string) => {
		const verdict = classifyReference(value);
		if (verdict.kind === 'ok') return;
		const line = lineAt(source, index);
		// A stylesheet has no TAG, and that empty string is load-bearing rather
		// than a placeholder: it is what makes `relativeExample` produce the
		// `url("image.png")` form here and an attribute form in HTML, and what
		// keeps the platform-library paragraph off a CSS refusal, where none of
		// the five hosted libraries could be the answer.
		failures.push(issue(path, line, referenceMessage(path, line, '', attr, value, verdict)));
	};

	// url( ... ) with or without quotes.
	const urlRe = /url\(\s*(?:"([^"]*)"|'([^']*)'|([^)'"\s]*))\s*\)/g;
	for (let m = urlRe.exec(text); m !== null; m = urlRe.exec(text)) {
		const value = m[1] ?? m[2] ?? m[3] ?? '';
		push(value, m.index, 'url');
	}

	// @import "x" -- the url() form is already caught above.
	const importRe = /@import\s+(?:"([^"]*)"|'([^']*)')/g;
	for (let m = importRe.exec(text); m !== null; m = importRe.exec(text)) {
		const value = m[1] ?? m[2] ?? '';
		push(value, m.index, 'url');
	}

	return { failures };
}

