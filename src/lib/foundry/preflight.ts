/**
 * THE NETWORK-API LIST IS GONE, and its absence is the point. `fetch`,
 * `XMLHttpRequest`, `WebSocket` and `EventSource` each earned a warning here
 * while the proxy sent `connect-src 'none'`, because the call really was dead.
 * There is no CSP on a bundle now, so all four work, and a warning about them
 * would be telling a student their working code is broken.
 *
 * WHAT REPLACED IT IS ABOUT STORAGE, AND STORAGE HAS NOW RELAXED TOO -- SO
 * THIS SENTENCE CHANGED WITH IT. It used to read: the frame is an opaque
 * origin, `window.localStorage` is not merely empty but THE GETTER THROWS, and
 * nothing survives a reload. Every clause of that was true while a bundle ran
 * on an opaque origin. `foundrySandboxFlags` grants `allow-same-origin`
 * whenever the bundle origin and the portal origin differ, which is every
 * production configuration, so a published app has a REAL storage area and
 * saved data survives a reload. Repeating the old sentence would tell a
 * student their working save slot does not work.
 *
 * SO THE WARNING NOW NAMES THE TWO THINGS THAT ARE STILL TRUE, and it is worth
 * being exact about why each survives:
 *
 *   1. STORAGE IS UNAVAILABLE OFF THE FILESYSTEM. The contract tells a student
 *      to open `index.html` directly and check the app works before uploading,
 *      and a `file://` document is denied storage in some browsers -- reading
 *      it throws there exactly as it used to throw in the frame. That is what
 *      the shim is still for, and why the contract still hands it out: it is
 *      what makes the app behave the same in both places.
 *   2. EVERY PUBLISHED APP SHARES ONE STORAGE AREA. Storage is keyed by ORIGIN
 *      and every published app answers on the apps origin, so an unprefixed
 *      key like `save` is a key any other published app can read and
 *      overwrite. Separating them would take a subdomain per app; nothing
 *      inside the sandbox can partition an origin from itself. A key prefix is
 *      the whole remedy and it is one the student has to write.
 *
 * IT IS STILL UNCONDITIONAL AND IT IS STILL NOT A FALSE POSITIVE WHEN THE SHIM
 * IS THERE. The key-collision half is true of a correctly shimmed app as well,
 * and detecting the shim to suppress it would trade a true sentence for a
 * heuristic, and would have to run over the whole bundle rather than one file.
 * (What IS shim-detected is the shim's own text, so the platform does not
 * warn about the snippet it handed out -- see `isStorageShim`.)
 */
const STORAGE_APIS = ['localStorage', 'sessionStorage'] as const;

/**
 * `lineOffset` IS WHAT LETS ONE SCANNER SERVE TWO CALLERS.
 *
 * A `.js` file is scanned as itself and the offset is 0. An INLINE `<script>`
 * is scanned as a fragment, and its line 1 is somewhere down the middle of an
 * HTML file -- so every line this produces has to be moved by the distance
 * between them. It is a parameter rather than a second scanner because the
 * alternative is two copies of every rule and every sentence in here, which is
 * the exact failure the whole module is arranged to prevent.
 *
 * IT MOVES THE NUMBER INSIDE THE MESSAGE, NOT JUST THE `line` FIELD. The
 * sentences are built from `where(path, line)`, so a caller that corrected only
 * the field would leave the student reading "index.html line 3" and looking at
 * the wrong line of a file they have to go and find.
 */
export function scanJs(
	path: string,
	source: string,
	lineOffset = 0
): {
	failures: FoundryIssue[];
	warnings: FoundryIssue[];
} {
	const failures: FoundryIssue[] = [];
	const warnings: FoundryIssue[] = [];
	const text = blankComments(source, true);

	const seen = new Set<string>();
	const pushImport = (value: string, index: number) => {
		const verdict = classifyReference(value);
		// A bare specifier ("react") is not a URL, but it is also not something
		// that resolves with no build step. It is left alone deliberately: this
		// gate is about URLs, and a bare specifier fails loudly in the browser
		// with a message of its own.
		//
		// AN `https://` SPECIFIER IS NOW `ok` AND FALLS OUT HERE. `import ... from
		// "https://esm.sh/react"` is an ordinary module import that works, and it
		// is one of the two shapes an AI tool writes when asked for React.
		if (verdict.kind === 'ok') return;
		/*
		 * AN ABSOLUTE SPECIFIER IS REFUSED HERE NOW, AND IT USED TO BE SKIPPED.
		 * While every remote import was already a failure, letting `/lib/x.js`
		 * fall through cost nothing visible -- a student writing one had a CDN
		 * import somewhere too and was refused for that. With remote imports
		 * allowed, this is the ONLY broken import shape left, and skipping it
		 * would mean the one import that genuinely cannot resolve is the one
		 * nothing says anything about.
		 */
		const line = lineAt(source, index) + lineOffset;
		const key = `${line}:${value}`;
		if (seen.has(key)) return;
		seen.add(key);
		const at = where(path, line);
		const file = value.split(/[?#]/)[0];
		const guess = file.slice(file.lastIndexOf('/') + 1) || 'library.js';
		const named = /\.[a-z0-9]{2,5}$/i.test(guess) ? guess : `${guess}.js`;

		failures.push(
			issue(
				path,
				line,
				`${at} imports from ${value}, which is a ${verdict.kind === 'scheme' ? `${verdict.scheme}: link` : 'path starting with a forward slash'} and will not resolve. Import a file from inside your app folder with a relative path, like import ... from "./${named}", or use a full https:// address.`
			)
		);
	};

	const patterns = [
		// import x from "spec" / export { x } from "spec"
		/(?:^|[^\w$.])(?:import|export)\b[^;'"`]*?\bfrom\s*["']([^"']+)["']/g,
		// import "spec"
		/(?:^|[^\w$.])import\s*["']([^"']+)["']/g,
		// import("spec")
		/(?:^|[^\w$.])import\s*\(\s*["']([^"']+)["']\s*\)/g
	];
	for (const re of patterns) {
		for (let m = re.exec(text); m !== null; m = re.exec(text)) {
			// The SPECIFIER'S own index, not the match's. See the note on the
			// storage loop below: the pattern opens with the character BEFORE
			// the keyword, and at column 0 that character is the previous line's
			// newline.
			pushImport(m[1], m.index + m[0].lastIndexOf(m[1]));
		}
	}

	/*
	 * THE IDENTIFIER'S INDEX, NOT THE MATCH'S, AND THE DIFFERENCE IS A WHOLE
	 * LINE.
	 *
	 * The pattern opens with `(?:^|[^\w$.])` so `myLocalStorage` does not match
	 * -- which means the match STARTS at the character before the identifier.
	 * When the statement is at column 0 that character is the newline ending the
	 * PREVIOUS line, and the reported line is one too early: measured on a plain
	 * .js file, a call on line 3 answered "app.js line 2" before this was fixed.
	 * Statements at column 0 are most of the statements anybody writes, so it was
	 * wrong more often than right. `m[0].indexOf(m[1])` steps over that leading
	 * character.
	 *
	 * ONE REGEX FOR BOTH NAMES rather than one per name, so the two cannot be
	 * spelled differently, and `m[1]` reports which was found.
	 *
	 * `window.localStorage` is deliberately NOT matched, for the same reason
	 * `this.fetch` was not: the leading class excludes a preceding dot. That is a
	 * miss rather than a bug -- this is advice, and the shim it points at fixes
	 * both spellings.
	 */
	const storageRe = /(?:^|[^\w$.])(localStorage|sessionStorage)\b/g;
	for (let m = storageRe.exec(text); m !== null; m = storageRe.exec(text)) {
		const api = m[1];
		const line = lineAt(source, m.index + m[0].indexOf(api)) + lineOffset;
		const key = `${line}:${api}`;
		if (seen.has(key)) continue;
		seen.add(key);
		warnings.push(
			issue(
				path,
				line,
				`${where(path, line)} uses ${api}. Published apps have a real storage area and saved data survives a reload, so this works. Two things still catch apps out. Every published app is served from the same address, so they all share one ${api}: prefix every key with your app's own name, like ${api}.setItem('my-app:save', value), or another app can read and overwrite it. And ${api} is blocked when ${FOUNDRY_ENTRY_FILE} is opened straight off your own computer, where reading it throws and stops the script, so paste the storage snippet from the build contract as the first thing inside <head> to make it behave the same in both places.`
			)
		);
	}

	return { failures, warnings };
}

