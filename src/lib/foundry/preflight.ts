export interface PlannedFile {
	path: string;
	/** Index into the record list the caller handed in. */
	index: number;
	declaredSize: number;
}

export interface StructurePlan {
	files: PlannedFile[];
	strippedWrapper: string | null;
	droppedOsNoise: number;
	/** Files dropped for their EXTENSION rather than for being zipper noise. */
	droppedIgnored: number;
	failures: FoundryIssue[];
	notes: string[];
}

export interface StructureInput {
	name: string;
	directory: boolean;
	irregular: boolean;
	declaredSize: number;
}

/**
 * Everything that can be decided from the archive's table of contents, before a
 * single byte is inflated. Runs identically in the browser and on the server.
 *
 * EVERY FAILURE IS COLLECTED rather than thrown on the first one. A student who
 * fixes one CDN link and re-uploads to find a second one is a student who
 * uploads five times; the whole list, once, is the point.
 */
export function planStructure(entries: StructureInput[], zipBytes: number): StructurePlan {
	const failures: FoundryIssue[] = [];
	const notes: string[] = [];

	if (zipBytes > FOUNDRY_LIMITS.maxZipBytes) {
		failures.push(
			issue(
				null,
				null,
				`The zip is ${formatBytes(zipBytes)}. The limit is ${formatBytes(FOUNDRY_LIMITS.maxZipBytes)}. Compress your images and audio, or take out files your app does not load, and upload again.`
			)
		);
	}

	let droppedOsNoise = 0;
	let droppedIgnored = 0;
	// PER EXTENSION, NOT ONE TOTAL. `FOUNDRY_IGNORED_EXTENSIONS` now holds two
	// entries (`.md`, `.map`), and a single joined "kinds" string would name
	// BOTH in the note even on an upload that dropped only one of them -- a
	// student reading "2 .md, .map files were left out" after shipping two
	// READMEs and no source map at all. One sentence per extension that this
	// upload actually dropped keeps that from happening as the ignored list
	// grows further.
	const droppedIgnoredByExt = new Map<string, number>();
	const kept: { name: string; index: number; declaredSize: number }[] = [];
	entries.forEach((entry, index) => {
		if (entry.directory) return;
		if (isOsNoise(entry.name)) {
			droppedOsNoise++;
			return;
		}
		/*
		 * BEFORE `judgeEntryName`, deliberately. Judging it first would push a
		 * README down the path that ends in the extension refusal below, and the
		 * whole point of this list is that it does not end there.
		 */
		if (isIgnoredExtension(entry.name)) {
			droppedIgnored++;
			const ext = extensionOf(entry.name);
			droppedIgnoredByExt.set(ext, (droppedIgnoredByExt.get(ext) ?? 0) + 1);
			return;
		}
		const judged = judgeEntryName(entry.name, entry.irregular);
		if ('rejection' in judged) {
			failures.push(entryRejectionIssue(entry.name, judged.rejection));
			return;
		}
		kept.push({ name: judged.path, index, declaredSize: entry.declaredSize });
	});

	if (droppedOsNoise > 0) {
		notes.push(
			droppedOsNoise === 1
				? 'One file your operating system added to the zip was left out. It is not part of your app.'
				: `${droppedOsNoise} files your operating system added to the zip were left out. They are not part of your app.`
		);
	}

	// Same shape as the note above: what went, and why it was not part of the
	// app. The extension is named because unlike operating-system noise this is
	// a file the student wrote on purpose and may be looking for afterwards.
	for (const ext of FOUNDRY_IGNORED_EXTENSIONS) {
		const count = droppedIgnoredByExt.get(ext) ?? 0;
		if (count === 0) continue;
		notes.push(
			count === 1
				? `One .${ext} file was left out. It cannot be part of a published app, and leaving it in would have stopped the upload.`
				: `${count} .${ext} files were left out. They cannot be part of a published app, and leaving them in would have stopped the upload.`
		);
	}

	// A traversal attempt is a security refusal and nothing else is reported
	// beside it. Continuing to talk about titles and file sizes under it would
	// bury the one line that matters.
	if (failures.some((f) => f.message.includes('points outside'))) {
		return { files: [], strippedWrapper: null, droppedOsNoise, droppedIgnored, failures, notes };
	}

	if (kept.length === 0 && failures.length === 0) {
		failures.push(
			issue(
				null,
				null,
				'That zip has no files in it. It needs to contain your app, with index.html at the top level.'
			)
		);
		return { files: [], strippedWrapper: null, droppedOsNoise, droppedIgnored, failures, notes };
	}

	const { paths, stripped } = stripWrapperDirectory(kept.map((k) => k.name));
	const strippedFiles: PlannedFile[] = kept.map((k, i) => ({
		path: paths[i],
		index: k.index,
		declaredSize: k.declaredSize
	}));

	if (stripped !== null) {
		notes.push(
			`Everything was inside a folder called "${stripped}", so that folder was removed and its contents are now the top level of your app. ${FOUNDRY_ENTRY_FILE} is where it needs to be.`
		);
	}

	// index.htm, or a single unambiguous top-level HTML file, is renamed to
	// the canonical entry name here -- before the checks below, so an
	// upload that resolves to one of those two shapes never hits the "no
	// index.html" refusal in the first place.
	const { files, note: entryNote } = resolveEntryFile(strippedFiles);
	if (entryNote !== null) notes.push(entryNote);

	if (files.length > FOUNDRY_LIMITS.maxFiles) {
		failures.push(
			issue(
				null,
				null,
				`The zip contains ${files.length} files. The limit is ${FOUNDRY_LIMITS.maxFiles}. Take out files your app does not load and upload again.`
			)
		);
	}

	if (!files.some((f) => f.path === FOUNDRY_ENTRY_FILE)) {
		failures.push(
			issue(
				null,
				null,
				`There is no ${FOUNDRY_ENTRY_FILE} at the top level of the zip. Your app has to start from a file named exactly ${FOUNDRY_ENTRY_FILE}, sitting at the top level. Rename your main page to ${FOUNDRY_ENTRY_FILE}, or make the zip from inside your app folder rather than from the folder above it, and upload again.`
			)
		);
	}

	const allowed = FOUNDRY_ALLOWED_EXTENSIONS.join(', ');
	for (const file of files) {
		const ext = extensionOf(file.path);
		if (ext === 'br' || ext === 'gz') {
			failures.push(issue(file.path, null, compressedExtensionMessage(file.path, ext)));
			continue;
		}
		if (!ALLOWED.has(ext)) {
			failures.push(
				issue(
					file.path,
					null,
					ext === ''
						? `${file.path} has no file extension, so there is no way to tell a browser what it is. Give it the extension that matches what it is, or take it out. The types this platform can serve are ${allowed}.`
						: `${file.path} is a .${ext} file, which this platform cannot serve. The types it can serve are ${allowed}. If this is a source file you build from, take it out and include only the finished files your page loads.`
				)
			);
		}
	}

	return { files, strippedWrapper: stripped, droppedOsNoise, droppedIgnored, failures, notes };
}

/**
 * `.br` AND `.gz` ARE REFUSED BY NAME RATHER THAN BY THE GENERIC "CANNOT
 * SERVE" SENTENCE, because the generic one's advice -- "take it out" or "give
 * it the right extension" -- is wrong here. A Brotli or gzip build is a real,
 * working build; what is missing is the `content-encoding` response header a
 * browser needs to decompress it on the way in, and this serving route does
 * not send one. Storing the file changes nothing: it would sit in the bucket
 * forever, byte-identical to what was uploaded, and never run. So the fix
 * named is the one that actually works -- export uncompressed -- not "remove
 * this file" or "rename it".
 */
function compressedExtensionMessage(path: string, ext: 'br' | 'gz'): string {
	const compression = ext === 'br' ? 'Brotli' : 'gzip';
	return `${path} is a .${ext} file: a ${compression}-compressed build output. This platform has no way to tell a browser it is ${compression}-compressed (that takes a content-encoding response header, and this platform does not send one for your files), so the bytes would arrive and never decompress. Turn off ${compression} compression in your engine's web export settings and upload the uncompressed build instead.`;
}

function entryRejectionIssue(name: string, rejection: EntryRejection): FoundryIssue {
	switch (rejection) {
		case 'escapes':
			return issue(
				null,
				null,
				`The zip contains an entry named ${name}, which points outside your app folder. Nothing was unpacked. Make the zip from inside your app folder, so every file in it sits under that folder.`
			);
		case 'absolute':
			return issue(
				null,
				null,
				`The zip contains an entry named ${name}, which is a full path from the top of a disk rather than a file inside your app folder. Nothing was unpacked. Make the zip from inside your app folder.`
			);
		case 'backslash':
			return issue(
				null,
				null,
				`The zip contains an entry named ${name}, which separates folders with a backslash. Nothing was unpacked. Re-make the zip with a tool that writes forward slashes, or compress the folder itself rather than adding files one at a time.`
			);
		case 'irregular':
			return issue(
				null,
				null,
				`${name} is a shortcut (a symbolic link) rather than a real file. Replace it with the actual file and zip your app again.`
			);
		default:
			return issue(
				null,
				null,
				`The zip contains an entry named ${name}, which is not a usable file path. Take it out and zip your app again.`
			);
	}
}

/** The message for the incremental cap, which only the server can reach. */
export function uncompressedCapMessage(stoppedAt: string): string {
	return `The files in this zip add up to more than ${formatBytes(FOUNDRY_LIMITS.maxTotalBytes)} once unpacked, so unpacking stopped partway (at ${stoppedAt}) and nothing was saved. The limit is ${formatBytes(FOUNDRY_LIMITS.maxTotalBytes)} unpacked. Take out or compress the largest files and upload again.`;
}

/** The message for an archive that is not a zip at all. */
export function unreadableZipMessage(): string {
	return 'That file could not be opened as a zip. Make a new one by selecting your app\'s files and compressing them, then upload that.';
}

/** A single asset large enough to be worth mentioning, but not to refuse. */
export function largeAssetWarning(path: string, bytes: number): FoundryIssue {
	return issue(
		path,
		null,
		`${path} is ${formatBytes(bytes)}. Files this large make your app slow to open, especially on a school laptop. Compress it or use a smaller one.`
	);
}

