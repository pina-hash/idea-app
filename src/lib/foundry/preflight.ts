/* -------------------------------------------------------------------------
 * Paths.
 * ---------------------------------------------------------------------- */

export type EntryRejection =
	| 'backslash'
	| 'absolute'
	| 'escapes'
	| 'irregular'
	| 'unusable';

/**
 * Judges one archive entry name.
 *
 * CONTAINMENT IS DECIDED BY RESOLVING THE PATH, not by looking for bad
 * substrings. `resolveInsideRoot` walks the segments the way a filesystem
 * would and reports whether the result is still under the root; a name that
 * climbs out at any point during the walk fails even if it climbs back in
 * afterwards. The substring rules in `bundlePathOk` are the SQL mirror and run
 * as well, so a stored path also satisfies `_classroom_deck_path_ok`.
 *
 * A BACKSLASH IS REFUSED HERE RATHER THAN REPAIRED, which is the one place
 * Foundry parts company with the deck reader. A deck export is machine-written
 * by a tool we control, so rewriting a Windows separator is a kindness. A
 * Foundry upload is arbitrary: `..\..\x` is a traversal attempt wearing a
 * different separator, and quietly rewriting an attacker's path into a legal
 * one is not a thing to do on a security boundary.
 */
export function judgeEntryName(
	name: string,
	irregular: boolean
): { path: string } | { rejection: EntryRejection } {
	if (irregular) return { rejection: 'irregular' };

	const raw = (name ?? '').trim();
	if (raw.length === 0) return { rejection: 'unusable' };
	if (raw.includes('\\')) return { rejection: 'backslash' };
	if (raw.startsWith('/')) return { rejection: 'absolute' };
	// A drive letter is an absolute path in the shape Windows writes it.
	if (/^[a-zA-Z]:/.test(raw)) return { rejection: 'absolute' };

	if (!resolveInsideRoot(raw)) return { rejection: 'escapes' };

	// `./x` is the same file as `x`; every zipper writes one or the other.
	let path = raw;
	while (path.startsWith('./')) path = path.slice(2);

	if (!bundlePathOk(path)) {
		// The only ways left to fail this are a `..` segment that resolved back
		// inside, a `.` segment, a doubled slash, or a colon.
		return { rejection: path.includes('..') ? 'escapes' : 'unusable' };
	}
	return { path };
}

/**
 * Walks the segments and reports whether the result stays under the root. A
 * `..` that pops past the root at ANY point is out, which is what makes
 * `a/../../x` fail even though it ends up one level down.
 */
export function resolveInsideRoot(path: string): boolean {
	const parts: string[] = [];
	for (const segment of path.split('/')) {
		if (segment === '' || segment === '.') continue;
		if (segment === '..') {
			if (parts.length === 0) return false;
			parts.pop();
			continue;
		}
		parts.push(segment);
	}
	return parts.length > 0;
}

/**
 * Operating-system metadata a zipper adds without being asked.
 *
 * DROPPED, AND REPORTED -- never silently. macOS writes `__MACOSX/` beside
 * every folder it compresses and `.DS_Store` inside it; Windows writes
 * `Thumbs.db` and `desktop.ini`. None of it is the student's work and none of
 * it would pass the extension allowlist, so leaving it in would refuse most
 * zips a Mac has ever made, over files the student cannot see in Finder and did
 * not know were there. That is the definition of a message that reads as
 * arbitrary rejection. They come out, and the count is reported.
 */
export function isOsNoise(name: string): boolean {
	if (name.startsWith('__MACOSX/') || name === '__MACOSX') return true;
	const base = name.slice(name.lastIndexOf('/') + 1);
	if (base === '.DS_Store' || base === 'Thumbs.db' || base === 'desktop.ini') return true;
	// The AppleDouble sidecar, which can also appear outside __MACOSX/.
	if (base.startsWith('._')) return true;
	return false;
}

/**
 * NOISE IN A PICKED FOLDER, which is a WIDER set than noise in a zip, and the
 * difference is deliberate.
 *
 * `isOsNoise` is what a ZIPPER added without being asked, and it is dropped on
 * both paths. This adds the two things a DEVELOPMENT FOLDER carries that a zip
 * of the same work usually would not: `.git`, because a student drags the
 * project folder rather than a copy of its output, and `node_modules`, because
 * a generated app that once ran a package manager still has one sitting there.
 * Neither is the student's app, both are enormous, and either would blow the
 * file cap long before anything about the app was looked at.
 *
 * IT IS NOT FOLDED INTO `isOsNoise`, because that would change what the SERVER
 * does with an uploaded zip: a zip containing `node_modules` is a student who
 * zipped the wrong folder, and the honest answer to that is the refusal they
 * already get, not a silent drop of half their archive. Here the folder is
 * being read file by file in front of them and the drop is reported before
 * anything is uploaded, which is a different situation with a different right
 * answer.
 *
 * Returns the LABEL to report, so the caller can say what went and why rather
 * than emitting a count of anonymous omissions.
 */
export function folderNoiseLabel(path: string): string | null {
	if (isOsNoise(path)) return 'operating system files';
	const segments = path.split('/');
	if (segments.includes('.git')) return '.git';
	if (segments.includes('node_modules')) return 'node_modules';
	return null;
}

/**
 * Removes a single wrapper directory when the whole app sits inside one.
 *
 * A FOLDER-OF-ONE IS THE SINGLE MOST COMMON SHAPE A PERSON UPLOADS -- right
 * click the folder, "Compress", and every path gains the folder's own name. So
 * this is a repair rather than a refusal, and it moves the whole tree together,
 * which changes no reference between the files.
 *
 * It strips ONE level and only when `index.html` is directly inside it. Not a
 * loop: two nested wrappers is a different mistake, and a loop that ate both
 * would also eat a real single-directory app whose entry sits deeper.
 */
export function stripWrapperDirectory(paths: string[]): {
	paths: string[];
	stripped: string | null;
} {
	if (paths.length === 0) return { paths, stripped: null };
	if (paths.includes(FOUNDRY_ENTRY_FILE)) return { paths, stripped: null };

	let root: string | null = null;
	for (const p of paths) {
		const slash = p.indexOf('/');
		// A file at the top level means there is no single wrapper to remove.
		if (slash < 0) return { paths, stripped: null };
		const first = p.slice(0, slash);
		if (root === null) root = first;
		else if (root !== first) return { paths, stripped: null };
	}
	if (root === null) return { paths, stripped: null };

	const prefix = `${root}/`;
	const inner = paths.map((p) => p.slice(prefix.length));
	if (!inner.includes(FOUNDRY_ENTRY_FILE)) return { paths, stripped: null };
	return { paths: inner, stripped: root };
}

/* -------------------------------------------------------------------------
 * Reference classification, shared by HTML and CSS.
 * ---------------------------------------------------------------------- */

export type RefVerdict = { kind: 'ok' } | { kind: 'absolute' } | { kind: 'scheme'; scheme: string };

/** A verdict that is actually a problem. Every message builder takes one. */
export type RefProblem = Exclude<RefVerdict, { kind: 'ok' }>;

/**
 * Schemes that are simply fine, and the reason each is on the list.
 *
 * `http`/`https` ARE ON IT NOW, and that is the relaxation. A bundle is served
 * from public Storage with no CSP of ours on it, so a CDN script tag, a Google
 * Fonts stylesheet and an `<img>` from another site all load exactly as they
 * would on any web page. Refusing them was correct while the proxy sent
 * `connect-src 'none'`; it is now refusing something that works, which is the
 * worst kind of gate -- it teaches a student that the platform is arbitrary,
 * and it fails the single most common thing an AI tool produces.
 *
 * `data:` is inlined and always was. `mailto:` and `tel:` open the device's
 * mail or phone app rather than fetching anything. `blob:` is a URL the app
 * minted for its own bytes.
 */
const ALLOWED_SCHEMES = ['http:', 'https:', 'data:', 'mailto:', 'tel:', 'blob:'];

/**
 * Decides what a `src`, `href` or `url()` value is.
 *
 * A fragment or a query with no path is the current document and is fine.
 *
 * WHAT IS LEFT TO REFUSE, now that the network is not a rule:
 *
 *   absolute   a leading slash. It resolves against the ORIGIN the bundle is
 *              served from, which is the Supabase project host, where the
 *              app's own folder is nowhere near the root. It has never
 *              resolved to anything useful and now it cannot be made to: there
 *              is no longer an exception for `/_platform`, because that path
 *              is on a different host and is written as a whole URL instead.
 *   scheme     anything else -- `file:`, `ftp:`, `chrome:`. A `file:` path is
 *              a real and common mistake (an app that worked because the
 *              author opened it off their desktop) and is worth naming.
 */
export function classifyReference(value: string): RefVerdict {
	const v = (value ?? '').trim();
	if (v === '') return { kind: 'ok' };
	if (v.startsWith('#') || v.startsWith('?')) return { kind: 'ok' };

	const lower = v.toLowerCase();
	if (ALLOWED_SCHEMES.some((sch) => lower.startsWith(sch))) return { kind: 'ok' };

	// Protocol-relative inherits the page's scheme, which is https here.
	if (v.startsWith('//')) return { kind: 'ok' };

	const scheme = /^([a-zA-Z][a-zA-Z0-9+.-]*):/.exec(v);
	if (scheme) return { kind: 'scheme', scheme: scheme[1].toLowerCase() };

	if (v.startsWith('/')) return { kind: 'absolute' };
	return { kind: 'ok' };
}

/**
 * A relative example in the same shape as the thing being refused.
 *
 * THE SHAPE HAS TO BE VALID IN THE LANGUAGE IT WILL BE PASTED INTO. An HTML
 * reference is an attribute, so `src="logo.png"` is right; a CSS reference is a
 * `url()` function, and `url="bg.png"` -- which this produced for every CSS
 * refusal until it was read back out of a browser -- is not CSS at all. It
 * would be pasted into a stylesheet, or into the tool that wrote the
 * stylesheet, and produce a second broken thing. The `attr` a CSS scan passes
 * is the literal string `url`, which is what makes the two cases separable
 * here rather than at every call site.
 */
/**
 * THE FALLBACK NAME COMES FROM THE TAG, because a URL frequently has no
 * filename to take one from and `file.css` was being offered for all of them.
 *
 * Measured on the fixture this lane exists for: `<script src="https://unpkg.com/lucide@latest">`
 * has no extension anywhere in it, so the guess failed and the message told a
 * student to write `src="file.css"` -- a stylesheet name, in a script tag,
 * for an icon library. Every one of those three is wrong, and the sentence was
 * going to be pasted back into the tool that generated the app.
 *
 * A tag knows what kind of file it wants, so it is the tag that answers.
 */
function fallbackName(tag: string): string {
	switch (tag.toLowerCase()) {
		case 'script':
			return 'library.js';
		case 'link':
			return 'styles.css';
		case 'img':
			return 'image.png';
		case 'video':
			return 'clip.mp4';
		case 'audio':
			return 'sound.mp3';
		case 'source':
			return 'media.mp4';
		case 'iframe':
			return 'page.html';
		default:
			// The CSS `url()` case, where `tag` is empty. A stylesheet's own
			// url() is nearly always an image or a font, never another sheet.
			return 'image.png';
	}
}

function relativeExample(tag: string, attr: string, value: string): string {
	const base = value.split(/[?#]/)[0];
	const guess = base.slice(base.lastIndexOf('/') + 1);
	const named = /\.[a-z0-9]{2,5}$/i.test(guess) ? guess : fallbackName(tag);
	return attr === 'url' ? `url("${named}")` : `${attr}="${named}"`;
}

/* -------------------------------------------------------------------------
 * Line lookup.
 * ---------------------------------------------------------------------- */

/**
 * The line a value sits on, found by locating the value in the ORIGINAL source.
 *
 * A DOM parser does not report source positions, and building one that does
 * would be a parser of our own -- exactly the over-building this component is
 * told not to do. Parsing to decide WHAT is wrong and searching to decide WHERE
 * gets an accurate line without a second parser, and the worst case when a
 * value appears twice is that a student is pointed at the first of two
 * identical mistakes.
 */
export class LineFinder {
	private readonly source: string;
	private readonly cursors = new Map<string, number>();
	constructor(source: string) {
		this.source = source;
	}
	find(needle: string): number | null {
		if (!needle) return null;
		const from = this.cursors.get(needle) ?? 0;
		let at = this.source.indexOf(needle, from);
		if (at < 0) {
			at = this.source.indexOf(needle);
			if (at < 0) return null;
		}
		this.cursors.set(needle, at + needle.length);
		let line = 1;
		for (let i = 0; i < at; i++) if (this.source.charCodeAt(i) === 10) line++;
		return line;
	}
}

/** Where an attribute's value sits in the source, exactly. */
export interface AttrSpan {
	/** Index of the value's first character. */
	start: number;
	/** Index one past the value's last character. */
	end: number;
	line: number;
}



function lineAt(source: string, index: number): number {
	let line = 1;
	for (let i = 0; i < index && i < source.length; i++) {
		if (source.charCodeAt(i) === 10) line++;
	}
	return line;
}

