/**
 * IGNORED RATHER THAN REFUSED: dropped on the way in, reported, upload
 * continues.
 *
 * A README is among the most common things a generation tool emits, and it
 * cannot execute, cannot be navigated to and cannot be served. Failing an
 * entire upload over one is the wrong trade: the student did nothing wrong,
 * the file is inert, and the only thing the refusal achieves is a round trip
 * to delete it.
 *
 * THIS IS THE SAME TREATMENT `isOsNoise` GETS AND FOR THE SAME REASON -- the
 * file is not part of the app and its presence says nothing about the app.
 * What separates the two lists is provenance rather than policy: OS noise is
 * what a ZIPPER added unasked, and this is what the AUTHOR added on purpose
 * and does not need here.
 *
 * KEEP THIS LIST SHORT AND INERT. An extension belongs here only if it can
 * neither run nor be served, so dropping it changes nothing about the app. A
 * `.ts` or a `.scss` is a SOURCE file, and a bundle containing one means the
 * student shipped the wrong folder -- that stays a refusal, because the
 * refusal is the thing that tells them.
 */
export const FOUNDRY_IGNORED_EXTENSIONS = ['md'] as const;

const IGNORED = new Set<string>(FOUNDRY_IGNORED_EXTENSIONS);

/** Whether a path is dropped-and-reported rather than refused. */
export function isIgnoredExtension(path: string): boolean {
	return IGNORED.has(extensionOf(path));
}

const ALLOWED = new Set<string>(FOUNDRY_ALLOWED_EXTENSIONS);

/**
 * Content type per extension, and never anything the client declared.
 *
 * A WRONG TYPE ON A .js OR .css FILE STOPS THE BROWSER EXECUTING IT, which is
 * why this is a table and not a guess. `charset=utf-8` on the text types
 * matters for the same reason it does for decks: the file is UTF-8 and a
 * browser left to sniff renders its punctuation as mojibake.
 */
const MIME_BY_EXT: Record<string, string> = {
	html: 'text/html; charset=utf-8',
	css: 'text/css; charset=utf-8',
	js: 'text/javascript; charset=utf-8',
	json: 'application/json; charset=utf-8',
	txt: 'text/plain; charset=utf-8',
	svg: 'image/svg+xml',
	png: 'image/png',
	jpg: 'image/jpeg',
	jpeg: 'image/jpeg',
	webp: 'image/webp',
	gif: 'image/gif',
	mp3: 'audio/mpeg',
	wav: 'audio/wav',
	ogg: 'audio/ogg',
	woff2: 'font/woff2',
	ttf: 'font/ttf',
	// The IANA-registered name. `image/x-icon` is the older de-facto spelling
	// and both work; this one is the one that is actually registered.
	ico: 'image/vnd.microsoft.icon'
};

/** Lowercased extension with no dot, or '' when the name carries none. */
export function extensionOf(path: string): string {
	const base = path.slice(path.lastIndexOf('/') + 1);
	const dot = base.lastIndexOf('.');
	if (dot <= 0) return '';
	return base.slice(dot + 1).toLowerCase();
}

export function foundryMime(path: string): string {
	return MIME_BY_EXT[extensionOf(path)] ?? 'application/octet-stream';
}

/** Text files are the ones worth scanning and worth decoding as UTF-8. */
export function isTextExtension(ext: string): boolean {
	return ext === 'html' || ext === 'css' || ext === 'js' || ext === 'json' || ext === 'txt';
}

/* -------------------------------------------------------------------------
 * Invocation eligibility.
 * ---------------------------------------------------------------------- */

/**
 * Whether a version's CURRENT status permits running ingest against it again.
 * Only `draft`. `submitted`, `approved` and `rejected` have already been
 * reviewed, or are waiting to be, and re-extracting over any of them is how a
 * bundle gets swapped for a different one after somebody signed off on it.
 *
 * THIS IS LOAD-BEARING, NOT DEFENSIVE. 0131 added the SELECT policy
 * `foundry-uploads` was missing, and that policy's side effect is that an
 * own-prefix overwrite of the UPLOADED ZIP is now reachable where it
 * previously failed on RLS (0130's UPDATE policy could not find the row to
 * act on without it). So a student CAN now replace the zip sitting at
 * `zip_path` after their version has already been reviewed. The only thing
 * that stops that swapped zip from ever being served is that re-running
 * ingest is unreachable off `draft` -- there is no second gate. The ingest
 * function checks this BEFORE it downloads, purges or writes anything, so a
 * refusal here leaves the version's existing `student_app_files` rows and
 * `foundry-bundles` objects exactly as they were.
 */
export function versionIsIngestable(status: string): boolean {
	return status === 'draft';
}

