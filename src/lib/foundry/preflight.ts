/**
 * FOUNDRY PREFLIGHT: the rules, and the sentences a student reads when one of
 * them refuses their upload.
 *
 * THIS MODULE IS THE ONE COPY. The ingest Edge Function (Deno) and the browser
 * preflight (`./preflight-browser.ts`) both import it, so a rule cannot be
 * enforced two ways or worded two ways. What is deliberately NOT here is
 * anything only a server can do: storage writes, the service-role client, and
 * the incremental uncompressed cap, which lives in `./zip.ts` because it has to
 * count bytes as they come out of the decompressor.
 *
 * WHY THE WORDING IS THE POINT. Nearly every app uploaded here was generated by
 * an AI tool, and a failure message is going to be pasted straight back into
 * that tool. So a message is a plain sentence that names the file, the line
 * where one can be determined, what is wrong, and what to do instead -- never a
 * code, never a rule name, never our vocabulary. "CSP violation: external
 * resource" tells a student nothing and tells the tool that generated their app
 * even less.
 *
 * THESE MESSAGES ARE WRITTEN AGAINST THE BUILD CONTRACT students are given:
 * one folder with index.html at the top level; vanilla HTML, CSS and JS with no
 * build step; every path relative and never starting with a forward slash; no
 * network at runtime; fonts from `/_platform/fonts.css`, which is the one
 * allowed absolute path; localStorage present but in memory and cleared on
 * reload; the sandbox blocking `window.parent`, `window.open`, navigation and
 * downloads. If that document's wording moves, these move with it.
 *
 * THE HTML AND CSS SCAN IS A USABILITY GATE, NOT A SECURITY BOUNDARY. Runtime
 * safety is the sandbox and the CSP, which land in the next lane. That is why
 * the HTML side takes a REAL PARSER (injected, because Deno and the browser
 * have different ones) rather than running a regex over attributes: a regex
 * over attributes produces false positives, and a false positive here reads to
 * a student as arbitrary rejection. It is also why nothing here chases exotic
 * syntax -- getting it slightly wrong costs a confusing message, not a hole.
 */

