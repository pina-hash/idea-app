/**
 * THE CONTRACT'S CORE -- every rule, generated from the constants the checks
 * read, so a cap change rewrites the document in the same commit.
 *
 * `foundryBuildContract()` IS THIS PLUS THE DEFAULT PREAMBLE, and every
 * profile is this plus a different one. There is exactly one copy of the rules
 * in the repo and six ways in to it; a profile that restated a rule would be
 * the second copy, and the second copy is the one that goes stale.
 */
function contractCore(): string {
	const mb = (bytes: number) => `${Math.round(bytes / (1024 * 1024))} MB`;
	const exts = FOUNDRY_ALLOWED_EXTENSIONS.map((e) => `.${e}`).join(' ');
	const ignoredExts = FOUNDRY_IGNORED_EXTENSIONS.map((e) => `.${e}`).join(', ');

	/**
	 * THE THREE OUTCOMES, WORKED OUT BY ASKING THE RULES RATHER THAN BY
	 * DESCRIBING THEM.
	 *
	 * This paragraph used to read "Do not produce a README, a package.json, a
	 * lockfile, a config file, or a build script. They are not used and several
	 * of them are refused." It was the one vague line in an otherwise exact
	 * document, and it was also WRONG: `package.json` and `package-lock.json`
	 * are `.json`, which is on the allowlist, so they upload perfectly happily.
	 * A student who deleted them on that advice deleted them for nothing, and a
	 * tool told "several of them are refused" cannot act on it at all.
	 *
	 * So each candidate is put through the SAME predicates the upload uses --
	 * `isIgnoredExtension` and the allowlist -- and sorted by what actually
	 * happens to it. The document cannot claim an outcome the code does not
	 * produce, because it is not claiming anything: it is reporting.
	 */
	const CANDIDATES = [
		'README.md',
		'package.json',
		'package-lock.json',
		'vite.config.js',
		'build.sh',
		'app.ts',
		'styles.scss',
		'bundle.js.map'
	];
	const outcome = (name: string): 'ignored' | 'refused' | 'kept' => {
		if (isIgnoredExtension(name)) return 'ignored';
		return ALLOWED.has(extensionOf(name)) ? 'kept' : 'refused';
	};
	const named = (kind: 'ignored' | 'refused' | 'kept') =>
		CANDIDATES.filter((c) => outcome(c) === kind).join(', ');

	const extraFileRules = [
		`      Dropped, and you are told:  ${named('ignored')}`,
		`      Refused, upload stops:     ${named('refused')}`,
		`      Uploaded but never used:   ${named('kept')}`,
		'  The last group is harmless and still pointless. Leave them out.'
	].join('\n');

	const refusedExamples = CANDIDATES.filter((c) => outcome(c) === 'refused')
		.map((c) => `.${extensionOf(c)}`)
		.join(', ');

	return `OUTPUT SHAPE
- Produce ONE folder.
- Put ${FOUNDRY_ENTRY_FILE} at the TOP LEVEL of that folder. Not in a subfolder.
- Everything else the app needs goes in that same folder, or in subfolders of it.
- Extra files are handled in one of three ways, and it is worth knowing which:
${extraFileRules}

TECHNOLOGY
- HTML, CSS and JavaScript. The files you write are the files that run.
- There is NO BUILD STEP. Nothing is compiled, bundled, transpiled or
  installed on the way in.
- Do not write a .ts, .jsx or .scss file. Those extensions are refused and the
  whole upload stops. Ship the .js and .css a build would have made.
- A framework is fine as long as it arrives at runtime. React with JSX works by
  loading React, ReactDOM and Babel from a CDN and marking your own script
  type="text/babel". Vue works the same way from its browser build.
- ES modules work: <script type="module" src="app.js"></script> with relative
  paths, and a full https:// address as a specifier works too.
- WebAssembly works, and .wasm is an allowed file type. So are the payload
  files an engine export ships beside it: .pck, .data, .mem, .bin.

PATHS
- Every path to a file of your own is RELATIVE. Write src="art/logo.png", not
  src="/art/logo.png".
- A path starting with a forward slash is REFUSED, with no exceptions. It is
  read against the address your app is served from, which is not this site and
  is not your folder, so it can never find anything.
- An address on another site is written in full, with https:// in front of it.
- Do not use ../ to climb above the folder. Nothing exists up there.
- Paths are case-sensitive. art/Logo.png and art/logo.png are different files.
- <base href="..."> WORKS, and it is the one way to make a page whose files
  live somewhere else resolve them. Use it when you are porting a page that
  already loads its assets from a CDN and you do not want to rewrite every
  path. It rewrites what EVERY relative src, href and url() on that page means,
  including the ones pointing at your own files, so it is all or nothing. The
  upload warns about it every time, for a reason worth reading twice: if that
  other address goes down, or a school network blocks it, your app is broken
  and nothing in your own folder changed. Ship the files yourself where you
  can.

THE NETWORK
- The app is on the open web. Loading a script, stylesheet, image, font or data
  file from another site WORKS, and so do fetch, XMLHttpRequest, WebSocket and
  EventSource.
- A CDN is fine. React and Babel from unpkg, a charting library from jsdelivr,
  a font from Google Fonts: all of these load as written.
- There is no build step, so a library has to be usable from a plain script
  tag or as an ES module. React with JSX works only if you also load Babel and
  mark the script type="text/babel", which is slower but is allowed.
- Anything you load from another site is out of your control. If that site is
  down or the school network blocks it, your app is broken and nothing here
  will have warned you. A file you ship inside your own folder never has that
  problem, so prefer one where you can.

FONTS
- ${PLATFORM_FONTS_URL} gives you the three IDEA
  families. Link it with the WHOLE address, exactly as written:
      <link rel="stylesheet" href="${PLATFORM_FONTS_URL}">
- It provides three families. Use them by name:
      font-family: 'Rajdhani', sans-serif;         body and display
      font-family: 'Orbitron', sans-serif;         titles
      font-family: 'Share Tech Mono', monospace;   code and metadata
- Do not write href="/_platform/fonts.css". A path starting with a forward
  slash is read against the address your app is served from, which is not this
  site, so it will not be found. That is refused at upload.
- Google Fonts works too, and so does shipping your own .woff2 or .ttf in the
  folder and @font-face-ing it with a relative path.

${STORAGE_SECTION}

${SANDBOX_SECTION}

FILE TYPES
- Allowed extensions, and nothing else:
      ${exts}
- A file with any other extension is refused, and the whole upload stops.
  Refused examples: ${refusedExamples}.
- These are DROPPED rather than refused. Leave them in if you like; they are
  removed on the way in and you are told what went:
      ${ignoredExts} files
      .DS_Store, Thumbs.db, desktop.ini, __MACOSX, and ._ sidecar files
      .git and node_modules, when you upload a folder rather than a zip

SIZE
- At most ${FOUNDRY_LIMITS.maxFiles} files.
- At most ${mb(FOUNDRY_LIMITS.maxTotalBytes)} for everything unpacked, and at most ${mb(FOUNDRY_LIMITS.maxZipBytes)} for the zip.
- A single file over ${mb(FOUNDRY_LIMITS.warnAssetBytes)} is allowed but warned about. Compress large images and
  audio before including them.

BEFORE YOU FINISH
- Open ${FOUNDRY_ENTRY_FILE} directly from the filesystem and confirm the app works, or
  works apart from the things it loads from other sites.
- Confirm no src, href or url() in any file starts with a forward slash.
- Confirm nothing uses ../ to climb above the folder.
- Confirm every localStorage and sessionStorage key starts with your app's own
  name, and that the storage snippet is the first thing inside <head> in
  ${FOUNDRY_ENTRY_FILE}.`;
}

