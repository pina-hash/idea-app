export interface FoundryIssue {
	/** The bundle-relative file, or null for a problem with the archive itself. */
	file: string | null;
	/** 1-based, when the source can be located. Null otherwise. */
	line: number | null;
	/**
	 * The whole sentence a student reads. Self-contained on purpose: it repeats
	 * the file and line, because this string gets pasted somewhere with no
	 * surrounding table.
	 */
	message: string;
}

function issue(file: string | null, line: number | null, message: string): FoundryIssue {
	return { file, line, message };
}

/** One decimal, so "31.2 MB" rather than "31.198242 MB". */
export function formatBytes(bytes: number): string {
	if (bytes < 1024) return `${bytes} bytes`;
	if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
	return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/* -------------------------------------------------------------------------
 * Paths.
 * ---------------------------------------------------------------------- */

export type EntryRejection =
	| 'backslash'
	| 'absolute'
	| 'escapes'
	| 'irregular'
	| 'unusable';

/**
 * Judges one archive entry name.
 *
 * CONTAINMENT IS DECIDED BY RESOLVING THE PATH, not by looking for bad
 * substrings. `resolveInsideRoot` walks the segments the way a filesystem
 * would and reports whether the result is still under the root; a name that
 * climbs out at any point during the walk fails even if it climbs back in
 * afterwards. The substring rules in `bundlePathOk` are the SQL mirror and run
 * as well, so a stored path also satisfies `_classroom_deck_path_ok`.
 *
 * A BACKSLASH IS REFUSED HERE RATHER THAN REPAIRED, which is the one place
 * Foundry parts company with the deck reader. A deck export is machine-written
 * by a tool we control, so rewriting a Windows separator is a kindness. A
 * Foundry upload is arbitrary: `..\..\x` is a traversal attempt wearing a
 * different separator, and quietly rewriting an attacker's path into a legal
 * one is not a thing to do on a security boundary.
 */
export function judgeEntryName(
	name: string,
	irregular: boolean
): { path: string } | { rejection: EntryRejection } {
	if (irregular) return { rejection: 'irregular' };

	const raw = (name ?? '').trim();
	if (raw.length === 0) return { rejection: 'unusable' };
	if (raw.includes('\\')) return { rejection: 'backslash' };
	if (raw.startsWith('/')) return { rejection: 'absolute' };
	// A drive letter is an absolute path in the shape Windows writes it.
	if (/^[a-zA-Z]:/.test(raw)) return { rejection: 'absolute' };

	if (!resolveInsideRoot(raw)) return { rejection: 'escapes' };

	// `./x` is the same file as `x`; every zipper writes one or the other.
	let path = raw;
	while (path.startsWith('./')) path = path.slice(2);

	if (!bundlePathOk(path)) {
		// The only ways left to fail this are a `..` segment that resolved back
		// inside, a `.` segment, a doubled slash, or a colon.
		return { rejection: path.includes('..') ? 'escapes' : 'unusable' };
	}
	return { path };
}

/**
 * Walks the segments and reports whether the result stays under the root. A
 * `..` that pops past the root at ANY point is out, which is what makes
 * `a/../../x` fail even though it ends up one level down.
 */
export function resolveInsideRoot(path: string): boolean {
	const parts: string[] = [];
	for (const segment of path.split('/')) {
		if (segment === '' || segment === '.') continue;
		if (segment === '..') {
			if (parts.length === 0) return false;
			parts.pop();
			continue;
		}
		parts.push(segment);
	}
	return parts.length > 0;
}

/**
 * Operating-system metadata a zipper adds without being asked.
 *
 * DROPPED, AND REPORTED -- never silently. macOS writes `__MACOSX/` beside
 * every folder it compresses and `.DS_Store` inside it; Windows writes
 * `Thumbs.db` and `desktop.ini`. None of it is the student's work and none of
 * it would pass the extension allowlist, so leaving it in would refuse most
 * zips a Mac has ever made, over files the student cannot see in Finder and did
 * not know were there. That is the definition of a message that reads as
 * arbitrary rejection. They come out, and the count is reported.
 */
export function isOsNoise(name: string): boolean {
	if (name.startsWith('__MACOSX/') || name === '__MACOSX') return true;
	const base = name.slice(name.lastIndexOf('/') + 1);
	if (base === '.DS_Store' || base === 'Thumbs.db' || base === 'desktop.ini') return true;
	// The AppleDouble sidecar, which can also appear outside __MACOSX/.
	if (base.startsWith('._')) return true;
	return false;
}

/**
 * NOISE IN A PICKED FOLDER, which is a WIDER set than noise in a zip, and the
 * difference is deliberate.
 *
 * `isOsNoise` is what a ZIPPER added without being asked, and it is dropped on
 * both paths. This adds the two things a DEVELOPMENT FOLDER carries that a zip
 * of the same work usually would not: `.git`, because a student drags the
 * project folder rather than a copy of its output, and `node_modules`, because
 * a generated app that once ran a package manager still has one sitting there.
 * Neither is the student's app, both are enormous, and either would blow the
 * file cap long before anything about the app was looked at.
 *
 * IT IS NOT FOLDED INTO `isOsNoise`, because that would change what the SERVER
 * does with an uploaded zip: a zip containing `node_modules` is a student who
 * zipped the wrong folder, and the honest answer to that is the refusal they
 * already get, not a silent drop of half their archive. Here the folder is
 * being read file by file in front of them and the drop is reported before
 * anything is uploaded, which is a different situation with a different right
 * answer.
 *
 * Returns the LABEL to report, so the caller can say what went and why rather
 * than emitting a count of anonymous omissions.
 */
export function folderNoiseLabel(path: string): string | null {
	if (isOsNoise(path)) return 'operating system files';
	const segments = path.split('/');
	if (segments.includes('.git')) return '.git';
	if (segments.includes('node_modules')) return 'node_modules';
	return null;
}

/**
 * Removes a single wrapper directory when the whole app sits inside one.
 *
 * A FOLDER-OF-ONE IS THE SINGLE MOST COMMON SHAPE A PERSON UPLOADS -- right
 * click the folder, "Compress", and every path gains the folder's own name. So
 * this is a repair rather than a refusal, and it moves the whole tree together,
 * which changes no reference between the files.
 *
 * It strips ONE level and only when `index.html` is directly inside it. Not a
 * loop: two nested wrappers is a different mistake, and a loop that ate both
 * would also eat a real single-directory app whose entry sits deeper.
 */
export function stripWrapperDirectory(paths: string[]): {
	paths: string[];
	stripped: string | null;
} {
	if (paths.length === 0) return { paths, stripped: null };
	if (paths.includes(FOUNDRY_ENTRY_FILE)) return { paths, stripped: null };

	let root: string | null = null;
	for (const p of paths) {
		const slash = p.indexOf('/');
		// A file at the top level means there is no single wrapper to remove.
		if (slash < 0) return { paths, stripped: null };
		const first = p.slice(0, slash);
		if (root === null) root = first;
		else if (root !== first) return { paths, stripped: null };
	}
	if (root === null) return { paths, stripped: null };

	const prefix = `${root}/`;
	const inner = paths.map((p) => p.slice(prefix.length));
	if (!inner.includes(FOUNDRY_ENTRY_FILE)) return { paths, stripped: null };
	return { paths: inner, stripped: root };
}

/* -------------------------------------------------------------------------
 * Reference classification, shared by HTML and CSS.
 * ---------------------------------------------------------------------- */

export type RefVerdict =
	| { kind: 'ok' }
	| { kind: 'absolute' }
	| { kind: 'scheme'; scheme: string }
	| { kind: 'google-fonts' };

/** A verdict that is actually a problem. Every message builder takes one. */
export type RefProblem = Exclude<RefVerdict, { kind: 'ok' }>;

const GOOGLE_FONT_HOSTS = ['fonts.googleapis.com', 'fonts.gstatic.com'];

/**
 * Schemes that carry no network request and so are not this gate's concern.
 * `data:` is inlined, and always was. `mailto:` and `tel:` open the device's
 * mail or phone app rather than fetching anything -- refusing them read as
 * arbitrary, because nothing about the sandbox or the CSP objects to either.
 */
const NO_NETWORK_SCHEMES = ['data:', 'mailto:', 'tel:'];

/**
 * Decides what a `src`, `href` or `url()` value is.
 *
 * A fragment or a query with no path is the current document and is fine.
 */
export function classifyReference(value: string): RefVerdict {
	const v = (value ?? '').trim();
	if (v === '') return { kind: 'ok' };
	if (v.startsWith('#') || v.startsWith('?')) return { kind: 'ok' };
	if (v === PLATFORM_FONTS_PATH) return { kind: 'ok' };

	const lower = v.toLowerCase();
	if (NO_NETWORK_SCHEMES.some((s) => lower.startsWith(s))) return { kind: 'ok' };

	// Protocol-relative: inherits the page's scheme and is still the network.
	if (v.startsWith('//')) {
		const host = v.slice(2).split('/')[0].toLowerCase();
		if (GOOGLE_FONT_HOSTS.includes(host)) return { kind: 'google-fonts' };
		return { kind: 'scheme', scheme: 'https' };
	}

	const scheme = /^([a-zA-Z][a-zA-Z0-9+.-]*):/.exec(v);
	if (scheme) {
		const name = scheme[1].toLowerCase();
		if (name === 'http' || name === 'https') {
			const host = v.replace(/^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//, '').split('/')[0].toLowerCase();
			if (GOOGLE_FONT_HOSTS.includes(host)) return { kind: 'google-fonts' };
		}
		return { kind: 'scheme', scheme: name };
	}

	if (v.startsWith('/')) return { kind: 'absolute' };
	return { kind: 'ok' };
}

/**
 * A relative example in the same shape as the thing being refused.
 *
 * THE SHAPE HAS TO BE VALID IN THE LANGUAGE IT WILL BE PASTED INTO. An HTML
 * reference is an attribute, so `src="logo.png"` is right; a CSS reference is a
 * `url()` function, and `url="bg.png"` -- which this produced for every CSS
 * refusal until it was read back out of a browser -- is not CSS at all. It
 * would be pasted into a stylesheet, or into the tool that wrote the
 * stylesheet, and produce a second broken thing. The `attr` a CSS scan passes
 * is the literal string `url`, which is what makes the two cases separable
 * here rather than at every call site.
 */
function relativeExample(attr: string, value: string): string {
	const base = value.split(/[?#]/)[0];
	const guess = base.slice(base.lastIndexOf('/') + 1) || 'file.css';
	const named = /\.[a-z0-9]{2,5}$/i.test(guess) ? guess : 'file.css';
	return attr === 'url' ? `url("${named}")` : `${attr}="${named}"`;
}

/* -------------------------------------------------------------------------
 * Line lookup.
 * ---------------------------------------------------------------------- */

/**
 * The line a value sits on, found by locating the value in the ORIGINAL source.
 *
 * A DOM parser does not report source positions, and building one that does
 * would be a parser of our own -- exactly the over-building this component is
 * told not to do. Parsing to decide WHAT is wrong and searching to decide WHERE
 * gets an accurate line without a second parser, and the worst case when a
 * value appears twice is that a student is pointed at the first of two
 * identical mistakes.
 */
export class LineFinder {
	private readonly source: string;
	private readonly cursors = new Map<string, number>();
	constructor(source: string) {
		this.source = source;
	}
	find(needle: string): number | null {
		if (!needle) return null;
		const from = this.cursors.get(needle) ?? 0;
		let at = this.source.indexOf(needle, from);
		if (at < 0) {
			at = this.source.indexOf(needle);
			if (at < 0) return null;
		}
		this.cursors.set(needle, at + needle.length);
		let line = 1;
		for (let i = 0; i < at; i++) if (this.source.charCodeAt(i) === 10) line++;
		return line;
	}
}

function lineAt(source: string, index: number): number {
	let line = 1;
	for (let i = 0; i < index && i < source.length; i++) {
		if (source.charCodeAt(i) === 10) line++;
	}
	return line;
}

/* -------------------------------------------------------------------------
 * HTML.
 * ---------------------------------------------------------------------- */

export interface HtmlRef {
	tag: string;
	attr: string;
	value: string;
}

export interface HtmlFacts {
	refs: HtmlRef[];
	title: string | null;
	/**
	 * The text of every `<script>` WITHOUT a `src`, in document order.
	 *
	 * The ones WITH a `src` are already covered as references, by the same rule
	 * that covers a stylesheet or an image; scanning their (empty) bodies would
	 * find nothing and reporting them twice would be worse than finding nothing.
	 */
	inlineScripts: string[];
}

/**
 * Supplied by the runtime: `DOMParser` in a browser, deno-dom on the server.
 * The RULES stay here; only the parsing differs, because that is the only part
 * that genuinely cannot be shared.
 */
export type HtmlReader = (html: string) => HtmlFacts;

export interface HtmlScan {
	failures: FoundryIssue[];
	warnings: FoundryIssue[];
	/** True when the parser could not read the page at all. See below. */
	parseFailed?: boolean;
	parseError?: string;
}

/** The first line with something on it, used as a fallback locator. */
function firstRealLine(text: string): string {
	for (const line of text.split('\n')) {
		if (line.trim() !== '') return line;
	}
	return '';
}

export function scanHtml(path: string, source: string, read: HtmlReader): HtmlScan {
	const failures: FoundryIssue[] = [];
	const warnings: FoundryIssue[] = [];

	let facts: HtmlFacts;
	try {
		facts = read(source);
	} catch (err) {
		/*
		 * A PAGE THE PARSER CANNOT READ IS A HARD FAIL, AND IT USED TO BE A
		 * WARNING. That is what let a bundle through with four CDN script tags
		 * in its head, and the trail is worth keeping because the old reasoning
		 * sounded right: the browser will still render the page, the CSP is
		 * what actually contains it, so a parse failure is not evidence of
		 * anything WRONG with the file. All true, and all beside the point.
		 *
		 * Every HTML rule in here runs off `facts`. When the read throws, this
		 * function returned zero failures -- which is the same answer it gives
		 * for a perfect file. `foundry-ingest` turned that into a warning
		 * reading "Your app was still saved", extraction ran, the version
		 * reached the review queue, a reviewer read a soft note and approved
		 * it, and the app was blank because the four scripts it needs were
		 * never going to load. MEASURED: with the reader stubbed to fail the
		 * way deno-dom does on a cold start, this exact file produced 0
		 * failures and 1 warning and would have been published.
		 *
		 * "We checked it and found nothing" and "we could not check it" have to
		 * be different ANSWERS, not different log lines. So the second one
		 * refuses. A student can upload again; nobody can approve an unchecked
		 * bundle.
		 *
		 * `parseFailed` is still reported alongside, because the caller logs it
		 * and because it is the difference between a file that is wrong and a
		 * parser that is broken.
		 */
		failures.push(
			issue(
				path,
				null,
				`${path} could not be read by the checker, so it has not been published. That is usually a problem on our end rather than a mistake in your file. Upload it again, and if it happens a second time tell your teacher, because nothing can be published until the check runs.`
			)
		);
		return {
			failures,
			warnings,
			parseFailed: true,
			parseError: err instanceof Error ? err.message : String(err)
		};
	}

	/*
	 * INLINE SCRIPTS, SCANNED WITH THE SAME SCANNER THE .js FILES GET.
	 *
	 * A single HTML file is a first-class submission shape, and in that shape
	 * ALL of the JavaScript is inline -- so without this every JS rule is
	 * switched off for what will be the most common upload. The scanner is
	 * `scanJs`, unchanged, handed a line offset.
	 *
	 * THE OFFSET IS FOUND BY LOCATING THE SCRIPT'S TEXT IN THE SOURCE, over a
	 * CARRIAGE-RETURN-STRIPPED COPY of both. An HTML parser normalizes CRLF to
	 * LF in the DOM, so on a file saved by a Windows editor the text the parser
	 * hands back is not a substring of the source at all and every lookup
	 * fails silently. Stripping a carriage return from both sides cannot change a line
	 * number, because line numbers are counts of `
`.
	 *
	 * A BLOCK THAT CANNOT BE LOCATED IS STILL SCANNED, at the offset of the
	 * last one that could be, and never at zero: zero would report line numbers
	 * measured from the top of the block as though they were measured from the
	 * top of the file, which is a confidently wrong line for a student to go
	 * and look at. `LineFinder` advances a cursor per needle, so two identical
	 * blocks resolve to their own positions in order.
	 */
	const scriptFinder = new LineFinder(source.replace(/\r/g, ''));
	let lastKnownStart = 1;
	for (const raw of facts.inlineScripts) {
		const text = raw.replace(/\r/g, '');
		if (text.trim() === '') continue;
		const start = scriptFinder.find(text) ?? scriptFinder.find(firstRealLine(text));
		if (start !== null) lastKnownStart = start;
		// `start` is the line the script's TEXT begins on, and that text's own
		// line 1 is that same line -- so the shift is `start - 1`.
		const result = scanJs(path, text, (start ?? lastKnownStart) - 1);
		failures.push(...result.failures);
		warnings.push(...result.warnings);
	}

	const finder = new LineFinder(source);
	for (const ref of facts.refs) {
		const verdict = classifyReference(ref.value);
		if (verdict.kind === 'ok') continue;
		const line = finder.find(ref.value);
		failures.push(issue(path, line, referenceMessage(path, line, ref.attr, ref.value, verdict)));
	}

	if (path === FOUNDRY_ENTRY_FILE) {
		const title = (facts.title ?? '').trim();
		if (facts.title === null) {
			warnings.push(
				issue(
					path,
					null,
					`${path} has no page title. Add one inside <head> so your app has a name in the browser tab and in the Foundry listing, like <title>My App</title>.`
				)
			);
		} else if (title === '') {
			warnings.push(
				issue(
					path,
					finder.find('<title'),
					`${path} has an empty page title. Put your app's name between the tags, like <title>My App</title>, so it has a name in the browser tab and in the Foundry listing.`
				)
			);
		}
	}

	return { failures, warnings };
}

function where(path: string, line: number | null): string {
	return line === null ? path : `${path} line ${line}`;
}

function referenceMessage(
	path: string,
	line: number | null,
	attr: string,
	value: string,
	verdict: RefProblem
): string {
	const at = where(path, line);
	if (verdict.kind === 'google-fonts') {
		return `${at} loads a font from Google Fonts. That is blocked: your app runs with no network access, so the font will never arrive. Delete this link and use the platform fonts instead, with <link rel="stylesheet" href="${PLATFORM_FONTS_PATH}">. That is the one absolute path your app is allowed to use.`;
	}
	if (verdict.kind === 'absolute') {
		return `${at} points at ${value}, which starts with a forward slash. A leading slash means the top of the whole site rather than your app folder, so it will not be found. Use a path relative to the file you are writing in, like ${relativeExample(attr, value)}. The only absolute path allowed is ${PLATFORM_FONTS_PATH}.`;
	}
	if (verdict.scheme === 'http' || verdict.scheme === 'https') {
		return `${at} loads ${value} from the internet. That is blocked: your app runs with no network access, so nothing will load from that address. Download the file into your app folder and point at it with a relative path, like ${relativeExample(attr, value)}.`;
	}
	return `${at} uses ${value}, a ${verdict.scheme}: link. Your app can only open files that are inside its own folder, so remove the ${verdict.scheme}: link, or replace it with a file you have included and a relative path, like ${relativeExample(attr, value)}.`;
}

