/**
 * THE COURSE GLOSSARY: engineering vocabulary autocorrect must never touch.
 *
 * This file is the reason the feature beside it is a CURATED MAP and not a
 * dictionary. A spell checker in a technical class is not merely unhelpful,
 * it is actively destructive and it is destructive INVISIBLY: `fillet` becomes
 * `fillet` -> `filet`, `chamfer` gets flagged as a typo for `chamber`, `kerf`
 * for `kern`, `deburr` for `debug`, `swarf` for `scarf`, `boss` and `web` and
 * `draft` read as ordinary English words used oddly. The student does not
 * notice, because a correction looks confident, and what an instructor reads
 * back is a note that says something the student did not write.
 *
 * So the rule runs the other way round from a spell checker's. Nothing is
 * corrected unless it is named in `MISSPELLINGS`, and nothing named HERE is
 * corrected even if it is: this list wins, always, and `autocorrect.ts`
 * consults it before the map rather than after.
 *
 * HOW TO ADD TO IT, and it is meant to be added to constantly. Put the word in
 * the right section below, lowercase, and that is the whole job -- the lookup
 * lowercases what it is handed, `GLOSSARY` is built from these arrays at
 * module load, and `tests/notebook-autocorrect.test.ts` asserts every entry is
 * lowercase and that no word sits in both this file and the misspelling map.
 * There is no registration step and no migration: it is plain data in the
 * notebook's own directory, next to the code that reads it.
 *
 * A WORD BELONGS HERE IF A STUDENT COULD REASONABLY WRITE IT IN A NOTEBOOK
 * ENTRY. It costs nothing to include a term the map would never have touched
 * anyway -- the list is checked first and short-circuits -- and it costs a
 * student's sentence to leave one out. When in doubt, add it.
 *
 * The plain-data convention (curriculum.ts / pathways.ts): no Svelte, no
 * `$lib/server`, no imports at all, so a node test reads exactly what the
 * editor reads.
 */

