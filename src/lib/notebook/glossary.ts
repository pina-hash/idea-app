/**
 * Every glossary word, lowercased, as one set.
 *
 * A `Set` rather than an array because the lookup runs on every word boundary
 * a student types, and this list is long by design and meant to get longer.
 */
export const GLOSSARY: ReadonlySet<string> = new Set<string>([
	...GLOSSARY_CAD,
	...GLOSSARY_TOLERANCE,
	...GLOSSARY_SHOP,
	...GLOSSARY_ROBOTICS,
	...GLOSSARY_PROCESS
]);

/** Every section, for the test that sweeps them and for a future picker. */
export const GLOSSARY_SECTIONS: Readonly<Record<string, readonly string[]>> = {
	cad: GLOSSARY_CAD,
	tolerance: GLOSSARY_TOLERANCE,
	shop: GLOSSARY_SHOP,
	robotics: GLOSSARY_ROBOTICS,
	process: GLOSSARY_PROCESS
};

/**
 * Is this word the course's, and therefore never autocorrect's business?
 *
 * Case-insensitive: a student writing `Fillet` at the start of a sentence is
 * writing the same word.
 */
export function inGlossary(word: string): boolean {
	return GLOSSARY.has(word.toLowerCase());
}
